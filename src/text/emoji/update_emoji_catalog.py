import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[3]
VERSION = "18.0.0"
SOURCE_SHA256 = "8f3735cda1f92a779d78af67cf86066bb1f07143dc22f2ac29394d9bc57ab21a"
MANIFEST = "src/media/fonts/generated/st_emoji_coverage.json"
OUTPUT = "src/text/emoji/generated/st_emoji_catalog_data.c"


def font_coverage(root):
    path = root / "src/media/fonts/generated/st_emoji_data.c"
    # Git's Windows text checkout policy must not change the glyph fingerprint.
    data = path.read_bytes().replace(b"\r\n", b"\n")
    # All three raster banks use these same mappings. Check that contract too.
    text = data.decode("ascii")
    if text.count(".mapping = emoji_mapping,") != 3 or text.count(".cluster_mapping = emoji_clusters,") != 3:
        raise ValueError("Picker coverage requires shared 8/14/16 emoji mappings; review the picker")
    singles = text.split("emoji_mapping[] = {", 1)[1].split("};", 1)[0]
    clusters = text.split("emoji_clusters[] = {", 1)[1].split("};", 1)[0]
    sequences = {chr(int(cp, 16)) for cp in re.findall(r"UINT32_C\(0x([0-9a-f]+)\)", singles)}
    for escaped in re.findall(r'\{"([^\"]+)"', clusters):
        sequences.add(bytes(int(x, 16) for x in re.findall(r"\\x([0-9a-f]{2})", escaped)).decode("utf-8"))
    return {"unicode_version": VERSION, "font_sha256": hashlib.sha256(data).hexdigest(),
            "sequences": [" ".join(f"{ord(cp):X}" for cp in s) for s in sorted(sequences)]}


def names(root):
    data = (root / f"src/text/emoji/data/emoji-test-{VERSION}.txt").read_bytes()
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA256:
        raise ValueError("Emoji names do not match the pinned Unicode input; update the picker pins")
    entries = []
    for line in data.decode("utf-8").splitlines():
        match = re.match(r"^([0-9A-F ]+)\s*; fully-qualified\s*# \S+ E[0-9.]+ (.+)$", line)
        if match:
            entries.append(("".join(chr(int(cp, 16)) for cp in match[1].split()), match[2]))
    if not entries:
        raise ValueError("No fully-qualified emoji: review the Unicode picker parser")
    return entries


def plain(text):
    return "".join(cp for cp in text if ord(cp) != 0xfe0f and not 0x1f3fb <= ord(cp) <= 0x1f3ff)


def family(text, canonical):
    key = plain(text)
    key = key.replace("\u200d♀", "").replace("\u200d♂", "")
    neutral = str.maketrans({0x1f468: 0x1f9d1, 0x1f469: 0x1f9d1,
                            0x1f466: 0x1f9d2, 0x1f467: 0x1f9d2,
                            0x1f474: 0x1f9d3, 0x1f475: 0x1f9d3})
    candidate = key.translate(neutral)
    irregular = {"🫱\u200d🫲": "🤝", "🧑\u200d❤\u200d🧑": "💑",
                 "🧑\u200d❤\u200d💋\u200d🧑": "💏", "🤴": "🫅", "👸": "🫅",
                 "🤰": "🫄", "🫃": "🫄", "🎅": "🧑\u200d🎄", "🤶": "🧑\u200d🎄",
                 "👫": "🧑\u200d🤝\u200d🧑", "👬": "🧑\u200d🤝\u200d🧑", "👭": "🧑\u200d🤝\u200d🧑"}
    candidate = irregular.get(candidate, candidate)
    if candidate in canonical:
        return candidate
    if key in canonical:
        return key
    return plain(text) if plain(text) in canonical else text


def catalog(root, coverage):
    all_names = names(root)
    canonical = {plain(text): text for text, _ in all_names}
    supported = {"".join(chr(int(cp, 16)) for cp in s.split()) for s in coverage["sequences"]}
    entries = [(text, name) for text, name in all_names if text in supported]
    if not entries:
        raise ValueError("No renderable picker emoji")
    groups = {}
    for i, (text, _) in enumerate(entries):
        groups.setdefault(family(text, canonical), []).append(i)
    representatives = {}
    for key, members in groups.items():
        representatives[key] = next((i for i in members if plain(entries[i][0]) == key), members[0])
    out = ["/* Generated by update_emoji_catalog.py; Unicode-3.0 data. */",
           '#include "st_emoji_catalog.h"', "", "const struct st_emoji_entry st_emoji_entries[] = {"]
    for text, name in entries:
        escaped = "".join(f"\\x{byte:02x}" for byte in text.encode("utf-8"))
        escaped_name = "".join(f"\\x{byte:02x}" for byte in name.encode("utf-8"))
        out.append(f'\t{{"{escaped}", "{escaped_name}", {representatives[family(text, canonical)]}}},')
    out += ["};", "const size_t st_emoji_entry_count = sizeof(st_emoji_entries) / sizeof(st_emoji_entries[0]);", ""]
    return "\n".join(out)


def validate_repository(root=ROOT):
    root = Path(root)
    manifest = json.loads((root / MANIFEST).read_text())
    actual = font_coverage(root)
    if manifest != actual:
        raise ValueError("Stale picker glyph coverage: run update_emoji_catalog.py --refresh-coverage")
    # A Unicode update must not silently leave the picker on another version.
    for component in ("grapheme", "width", "normalization", "compare"):
        script = root / f"src/text/unicode_{component}/update_unicode_{component}.py"
        match = re.search(r'^VERSION\s*=\s*"([^"]+)"', script.read_text(), re.M)
        if match and match[1] != VERSION:
            raise ValueError(f"Unicode {component} and picker versions differ; update picker names, pins and tests")
    if (root / OUTPUT).read_text() != catalog(root, manifest):
        raise ValueError("Stale emoji picker catalog: regenerate update_emoji_catalog.py and review variant tests")


def refresh_repository(root=ROOT):
    root = Path(root)
    manifest = font_coverage(root)
    (root / MANIFEST).write_text(json.dumps(manifest, indent=2) + "\n")
    (root / OUTPUT).write_text(catalog(root, manifest), encoding="ascii")
    validate_repository(root)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--refresh-coverage", action="store_true")
    args = parser.parse_args()
    if args.refresh_coverage:
        (args.root / MANIFEST).write_text(json.dumps(font_coverage(args.root), indent=2) + "\n")
    if not args.check:
        manifest = json.loads((args.root / MANIFEST).read_text())
        (args.root / OUTPUT).write_text(catalog(args.root, manifest), encoding="ascii")
    validate_repository(args.root)


if __name__ == "__main__":
    main()
