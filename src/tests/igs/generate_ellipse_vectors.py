selections=model.selections;tables=model.tables;user=model.user;arithmetic=model.arithmetic;oracle=model.oracle
cases=[]
def add(res,mode,selection,radii,perimeter,center=(80,80),clip=True,bounds=None,app=False):
    xr,yr=radii
    cases.append(dict(gdp=5,resolution=res,mode=mode,selection=selection,radius=xr,radius_y=yr,perimeter=perimeter,
        center=center,clipping=clip,bounds=bounds,last=bool((mode+xr+yr)%2),app=app))
for res,mode,selection,radii,perimeter in itertools.product(range(3),range(1,5),range(39),((17,9),(9,17)),range(2)):
    add(res,mode,selection,radii,perimeter,app=radii==(17,9) and selections[selection][:2] in ((1,1),(3,12)))
for res,mode,radii,perimeter in itertools.product(range(3),range(1,5),
        ((0,0),(1,0),(0,1),(0,17),(17,0),(1,1),(2,7),(7,2),(31,4),(4,31),
         (127,3),(3,127),(128,3),(3,128),(131,3),(3,131),(132,3),(3,132),
         (511,3),(3,511),(512,3),(3,512),(515,3),(3,515),(516,3),(3,516),
         (-17,9),(17,-9),(-17,-9),(-1,1),(1,-1),(-3,0),(0,-3),(-127,3),(3,-127)),range(2)):
    add(res,mode,38,radii,perimeter)
for res,steps,vertical in itertools.product(range(3),range(32,129),range(2)):
    add(res,3,1,(3,4*steps) if vertical else (4*steps,3),1)
for res,mode,radii,perimeter,bounds in itertools.product(range(3),range(1,5),((17,9),(132,37)),range(2),
        ((50,45,105,95),(150,150,160,160),(0,150,20,160),(80,70,40,36))):
    add(res,mode,38,radii,perimeter,center=(80,60),bounds=bounds)
for res,mode,radii,perimeter,clip in itertools.product(range(3),range(1,5),((17,9),(-3,2),(2,-3)),range(2),(False,True)):
    add(res,mode,38,radii,perimeter,center=(3,4),clip=clip)
for res in range(3):
    for mode,perimeter in itertools.product(range(1,5),range(2)):
        add(res,mode,1,(132,17),perimeter,center=(80,60),bounds=(0,77,319 if res==0 else 639,77))
    for radii in ((9999,17),(17,9999)):add(res,3,1,radii,1)


header=['/* Generated by src/tests/igs/generate_ellipse_vectors.py; see ellipse-vectors.json provenance. */','static const struct ellipse_case ellipse_cases[] = {']
