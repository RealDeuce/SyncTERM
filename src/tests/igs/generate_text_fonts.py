#!/usr/bin/env python3
"""Maintainer import: original TOS glyph forms to decoded one-byte masks.

Usage: python3 -B src/tests/igs/generate_text_fonts.py /path/to/IGS
Normal builds/tests use checked-in masks and do not need the reference tree.
"""
# Copyright (c) 2026 Stephen Hurd; SPDX-License-Identifier: BSD-2-Clause
import hashlib
import json
from pathlib import Path
import struct
import sys
reference=Path(sys.argv[1]).resolve();source=reference/'docs/igs/generated/tos104-fonts.json'
fonts=json.loads(source.read_text());root=Path(__file__).resolve().parents[2]
lines=['/* Original Atari TOS1.04 system glyphs, decoded at import.',
       ' * Generated by generate_text_fonts.py; provenance: src/tests/igs/text-fonts.json. */',
       '/* Copyright (c) 2026 Stephen Hurd; SPDX-License-Identifier: BSD-2-Clause */',
       '#include "cterm_igs_fonts.h"','','#include <stddef.h>','']
decoded=[];records=[]
for f in fonts:
    width=f['max_cell_width'];height=f['form_height'];bitmap=bytes.fromhex(f['bitmap_hex']);pixels=[]
    assert f['first']==0 and f['last']==255 and len(f['offsets'])==257
    for character in range(256):
        assert f['offsets'][character+1]-f['offsets'][character]==width
        glyph=[]
        for y in range(height):
            row=[]
            for x in range(width):
                bit=f['offsets'][character]+x;value=(bitmap[y*f['form_width']+bit//8]>>(7-bit%8))&1
                row.append(value)
            assert ''.join('#' if bit else '.' for bit in row)==f['glyphs'][character][y]
            glyph+=row
        pixels+=glyph
    lines.append(f'static const uint8_t glyphs_{f["point"]}[] = {{')
    stride=width*height
    for character in range(256):lines.append('\t/* %02x */ '%character+','.join(map(str,pixels[character*stride:(character+1)*stride]))+',')
    lines+=['};',''];decoded.append(pixels)
    records.append(dict(symbol=f['symbol'],name=f['name'],point=f['point'],width=width,height=height,
                        bitmap_sha256=hashlib.sha256(bitmap).hexdigest(),
                        offsets_sha256=hashlib.sha256(b''.join(struct.pack('>H',v) for v in f['offsets'])).hexdigest(),
                        decoded_sha256=hashlib.sha256(bytes(pixels)).hexdigest()))
lines.append('static const struct cterm_igs_font fonts[] = {')
for doubled in (False,True):
    factor=2 if doubled else 1
    for f in fonts:
        values=[f['point']*factor,*[f[k]*factor+int(doubled) for k in ('top','ascent','half')],
                *[f[k]*factor for k in ('descent','bottom','max_char_width','max_cell_width','left_offset','right_offset','thicken','ul_size')],
                f['lighten'],f['skew'],f['max_cell_width'],f['form_height']]
        lines.append('\t{'+','.join(map(str,values))+','+('true' if doubled else 'false')+f',glyphs_{f["point"]}'+'},')
lines+=['};','','const struct cterm_igs_font *','cterm_igs_font_for_points(int points)','{',
        '\tsize_t selected = 0;', '\tfor (size_t i = 1; i < sizeof(fonts)/sizeof(*fonts); ++i)',
        '\t\tif (points >= fonts[i].points) selected = i;', '\treturn &fonts[selected];','}']
(root/'terminal/cterm/cterm_igs_fonts.c').write_text('\n'.join(lines)+'\n')
provenance=dict(generator='src/tests/igs/generate_text_fonts.py',source='generated/tos104-fonts.json',
    source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),rom_sha256=hashlib.sha256((reference/'TOS/tos104.img').read_bytes()).hexdigest(),
    method='Decode original packed font forms using their original offset tables; cross-check every decoded row against the independent exported glyph arrays. Six native metric records include exact doubled top/ascent/half rules.',
    original_glyphs=768,decoded_bytes=sum(map(len,decoded)),fonts=records,
    references=['04-text-console.adoc','30-native-font-sizing.adoc','32-native-physical-font-init.adoc'])
(Path(__file__).parent/'text-fonts.json').write_text(json.dumps(provenance,indent=2)+'\n')
print('Imported768 original glyphs as',sum(map(len,decoded)),'decoded mask bytes.')
