import hashlib
import itertools
import json
import re
import sys
from pathlib import Path

reference = Path(sys.argv[1]).resolve()
sys.path.insert(0,str(reference/'tools'))
from verify_tos104_rectangles import fixture, expected, PATTERN, SCREEN

source = (reference/'docs/igs/pattern-acceptance-data.adoc').read_text()
tables = json.JSONDecoder().raw_decode(source[source.index('{'):])[0]
user = [0,65535,0xa531,0x8001,0x5555,0xaaaa,0x0010,0x7ffe,
        0xf00f,0x00ff,0xff00,0x1357,0x2468,0x1111,0x8888,0x5aa5]
selections = [(0,1,[0]),(1,1,[65535])]
for interior,family,count,size,start in [(2,'DITHER',8,4,1),(2,'OEMPAT',16,8,9),
                                         (3,'HATCH0',6,8,1),(3,'HATCH1',6,16,7)]:
    rows = tables['tables']['_'+family]['words']
    assert len(rows) == count*size
    selections += [(interior,start+i,rows[i*size:(i+1)*size]) for i in range(count)]
selections += [(4,1,user)]
cases = []
for resolution,mode,selection,order in itertools.product(range(3),range(1,5),range(39),range(4)):
    x1,y1,x2,y2 = 13,11,54,43
    points = [x2 if order&1 else x1,y2 if order&2 else y1,x1 if order&1 else x2,y1 if order&2 else y2]
    bounds = (20,17,50,37) if order == 2 else (100,100,110,110) if order == 3 else None
    cases.append(dict(resolution=resolution,mode=mode,selection=selection,points=points,
                      bounds=bounds,clipping=True,perimeter=order%2,last=order%2,
                      app=order == 0 and selections[selection][:2] in [(0,1),(1,1),(2,4),(2,24),(3,12)]))
for resolution,mode,points,clipping in itertools.product(range(3),range(1,5),
        [(0,0,0,0),(15,31,16,32),(80,80,13,80),(40,80,40,11),(-4,-3,24,25)], [False,True]):
    cases.append(dict(resolution=resolution,mode=mode,selection=38,points=points,
                      bounds=(5,7,75,70) if clipping else None,clipping=clipping,perimeter=1,last=0,app=False))


def digest(words):
    result = 14695981039346656037
    for word in words:
        for byte in (word>>8,word&255): result = ((result^byte)*1099511628211)&0xffffffffffffffff
    return result


def runs(words,width,height,planes):
    result = []
    for y in range(height):
        row = [sum(((words[y*width*planes//16+(x//16)*planes+p]>>(15-x%16))&1)<<p
                   for p in range(planes)) for x in range(width)]
        start = 0
        while start < width:
            end = start+1
            while end < width and row[end] == row[start]: end += 1
            if row[start]: result.append((y,start,end-start,row[start]))
            start = end
    return result


header = ['/* Generated by src/tests/igs/generate_rectangle_vectors.py; see rectangle-vectors.json provenance. */',
          'static const struct rectangle_case rectangle_cases[] = {']
application = []
for number,case in enumerate(cases):
    res = case['resolution'];planes = (4,2,1)[res];hashes=[]
    interior,index,rows = selections[case['selection']]
    oracle_clip = case['bounds'] or (0,0,319 if res==0 else 639,399 if res==2 else 199)
    for phase in range(2):
        b,_ = fixture(case['points'],planes=planes,mode=case['mode']-1,mask=len(rows)-1,clip=case['bounds'])
        for offset in range(0,32000,2):
            plane = offset//2%planes
            b.words[SCREEN+offset] = (0x5aa5^(plane*0x1357)) if phase == 0 else (0xa55a^(plane*0x2468))
        for i,row in enumerate(rows):b.words[PATTERN+2*i] = row
        out,_ = expected(b,case['points'],planes=planes,mode=case['mode']-1,mask=len(rows)-1,clip=oracle_clip)
        hashes.append(digest([out[SCREEN+offset] for offset in range(0,32000,2)]))
    if case['app']:
        b,_ = fixture(case['points'],planes=planes,mode=case['mode']-1,mask=len(rows)-1)
        b.words.update({SCREEN+offset:0 for offset in range(0,32000,2)})
        for i,row in enumerate(rows):b.words[PATTERN+2*i] = row
        out,_ = expected(b,case['points'],planes=planes,mode=case['mode']-1,mask=len(rows)-1)
        words = [out[SCREEN+offset] for offset in range(0,32000,2)]
        application.append(dict(resolution=res,mode=case['mode'],interior=interior,index=index,
                                points=case['points'],rows=rows,runs=runs(words,320 if res==0 else 640,400 if res==2 else 200,planes)))
    values = [res,case['mode'],interior,index,int(case['clipping']),case['perimeter'],case['last']]
    bounds = case['bounds'] or (0,0,319 if res==0 else 639,399 if res==2 else 199)
    header.append('\t{'+','.join(map(str,values))+',{'+','.join(map(str,case['points']))+'},{'+
                  ','.join(map(str,bounds))+'},{UINT64_C(0x%016x),UINT64_C(0x%016x)}},'%tuple(hashes))
    if number%250 == 0:print(f'{number}/{len(cases)}',flush=True)
header.append('};')
models = ['verify_tos104_rectangles.py','verify_tos104_lines.py']
provenance = dict(generator='src/tests/igs/generate_rectangle_vectors.py',
    references=['15-graphics-commands.adoc','29-native-workstation-state.adoc','47-native-rectangles.adoc',
                '131-patterns-acceptance.adoc','134-delivery-rectangles.adoc'],
    method='Independent coordinate/plane-bit rectangle oracle and original literal fill rows; no SyncTERM output or Atari instruction execution.',
    rom_sha256=tables['rom_sha256'], table_sha256={k:v['sha256'] for k,v in tables['tables'].items() if k in ['_HOLLOW','_SOLID','_DITHER','_OEMPAT','_HATCH0','_HATCH1']},
    model_sha256={name:hashlib.sha256((reference/'tools'/name).read_bytes()).hexdigest() for name in models},
    native_cases=len(cases),native_foreground='Physical5 masked to active depth; effective logical pen7 retained across mode changes',
    native_initial='Each native word: primary 0x5aa5 XOR plane*0x1357, alternate 0xa55a XOR plane*0x2468',
    application_foreground='Wire C2,7 selects physical5 in low resolution and falls back to logical1/active mask in medium and mono. Zero-background run coverage is recoloured to that independent pen result; XOR uses the active mask.',
    native_hash='FNV-1a-64 over all32000 big-endian native bytes, each phase independently')
root = Path(__file__).resolve().parents[2]
(root/'terminal/cterm/tests/data/igs_rectangle_vectors.h').write_text('\n'.join(header)+'\n')
# Keep numeric rows, coordinates and pixel runs on one line for review.
encoded = json.dumps(dict(provenance=provenance,user=user,cases=application),indent=2)
encoded = re.sub(r'\[\s*(-?\d+(?:,\s*-?\d+)*)\s*\]',
                 lambda m:'['+', '.join(re.findall(r'-?\d+',m.group(1)))+']',encoded)
(Path(__file__).parent/'rectangle-vectors.json').write_text(encoded+'\n')
print(f'Wrote {len(cases)} native and {len(application)} application cases.',flush=True)
