#!/usr/bin/env python3
"""Maintainer import: source font rows and console-c composition inputs.

Usage: python3 -B src/tests/igs/generate_console_color_vectors.py /path/to/IGS
No SyncTERM output constructs expectations. Normal tests use the checked-in JSON.
"""
# Copyright (c) 2026 Stephen Hurd; SPDX-License-Identifier: BSD-2-Clause
import hashlib
import itertools
import json
from pathlib import Path
import sys
root=Path(sys.argv[1]).resolve();source=root/'docs/igs/generated/tos104-fonts.json'
fonts=json.loads(source.read_text());cases=[]
for res,state,selector,color,reverse in itertools.product(range(3),range(6),(0,1,2),(65,128),(False,True)):
    cases.append(dict(resolution=res,state=state,selector=selector,color=color,reverse=reverse,background=0))
for res,fg in itertools.product(range(3),range(16)):
    cases.append(dict(resolution=res,state=0,selector=1,color=fg,reverse=False,background=15-fg))
for res,pair,reverse in itertools.product(range(3),((0,0),(0,7),(1,27),(2,7),(4,27),(5,27)),(False,True)):
    state,color=pair
    cases.append(dict(resolution=res,state=state,selector=1,color=color,reverse=reverse,background=0))
for res,color in itertools.product(range(3),(0,15,16,31,32,255,256,9999)):
    cases.append(dict(resolution=res,state=0,selector=1,color=color,reverse=False,background=0))
for res,selector,color,reverse in itertools.product(range(3),(0,1),(65,128),(False,True)):
    cases.append(dict(resolution=res,state=6,selector=selector,color=color,reverse=reverse,background=2,wrap=True))
for res,color,reverse in itertools.product(range(3),(9,10),(False,True)):
    cases.append(dict(resolution=res,state=2,selector=1,color=color,reverse=reverse,background=0))
assert len(cases)==360
del_cases=[dict(resolution=res,state=4,selector=1,color=127,reverse=reverse,background=0)
           for res,reverse in itertools.product(range(3),(False,True))]
# Independent native console-glyph expectations include every printable byte.
header=['/* Source TOS font rows; generated by generate_console_color_vectors.py. */',
        'static const uint8_t console_source_rows[2][256][16] = {']
for font in fonts[1:]:
    header.append('\t{')
    for glyph in font['glyphs']:
        values=[int(row.replace('.','0').replace('#','1'),2) for row in glyph]
        header.append('\t\t{'+','.join('0x%02x'%value for value in values)+'},')
    header.append('\t},')
header.append('};')
(Path(__file__).resolve().parents[2]/'terminal/cterm/tests/data/igs_console_color_glyphs.h').write_text('\n'.join(header)+'\n')
data=dict(provenance=dict(generator='src/tests/igs/generate_console_color_vectors.py',
    references=['14-console-commands.adoc','66-native-console-pixels.adoc','195-delivery-console.adoc'],
    method='Literal original font rows and source-defined selector/raw-byte/persistent six-state console composition. Native and application tests use separate source-derived state interpreters; no SyncTERM output.',
    font_export_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),rom_sha256=hashlib.sha256((root/'TOS/tos104.img').read_bytes()).hexdigest(),
    native_printable_glyph_cases=2688,native_word_cases=1179648,native_color_pair_cases=1536,native_prior_state_cases=3696,application_cases=len(cases),del_application_cases=len(del_cases)),
    fonts={str(f['form_height']):{str(c):[int(row.replace('.','0').replace('#','1'),2) for row in f['glyphs'][c]] for c in (65,98,99,127,128)} for f in fonts[1:]},cases=cases,del_cases=del_cases)
(Path(__file__).parent/'console-color.json').write_text(json.dumps(data,indent=2)+'\n')
print('Wrote360 independent console composition scenes and literal font rows.')
