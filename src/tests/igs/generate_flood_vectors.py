from filled_curve_oracle import NativeFilledCurves,digest,runs
reference=Path(sys.argv[1]).resolve();model=NativeFilledCurves(reference)
sys.path.insert(0,str(reference/'tools'))
from verify_tos104_lines import bit_rule

patterns=[[[0]*17 for _ in range(9)],
 [[1 if x in (0,16) or y in (0,8) else 0 for x in range(17)] for y in range(9)],
 [[0 if (y in (1,7) and 1<=x<=15) or (x in (1,15) and 1<=y<=7) else 1 for x in range(17)] for y in range(9)],
 [[0 if x%4==1 or y%4==1 else 1 for x in range(17)] for y in range(9)],
 [[int((x+y)%2==1) for x in range(17)] for y in range(9)],
 [[0 if (x*11+y*7)%13<9 else 1 for x in range(17)] for y in range(9)]]
grids=[[[1]*19]+[[1]+row+[1] for row in grid]+[[1]*19] for grid in patterns]
cases=[]
def add(res,mode,selection,shape,perimeter,clip=False,bounds=None,seed=(2,2),origin=(40,60),app=False,text_after=False):
    cases.append(dict(resolution=res,mode=mode,selection=selection,shape=shape,perimeter=perimeter,clipping=clip,
                      bounds=bounds,seed=seed,origin=origin,app=app,text_after=text_after))
for res,mode,selection,shape in itertools.product(range(3),range(1,5),range(39),range(6)):
    add(res,mode,selection,shape,(selection+shape)%2,app=selection in (1,37))
for res,mode,selection in itertools.product(range(3),range(1,5),range(39)):
    add(res,mode,selection,0,1-selection%2)
for res,mode,shape,bounds in itertools.product(range(3),range(1,5),range(6),((1,1,10,7),(8,4,16,9),(14,7,5,4),(0,2,18,2))):
    add(res,mode,38,shape,1,clip=True,bounds=bounds)
for res,mode,shape in itertools.product(range(3),range(1,5),range(6)):
    add(res,mode,38,shape,1,seed=(9,5))
for res,mode,perimeter in itertools.product(range(3),range(1,5),range(2)):
    add(res,mode,37,3,perimeter,origin=(90,18*(16 if res==2 else 8)-3),app=True,text_after=True)

def oracle(case,phase,application=False):
    res=case['resolution'];planes=(4,2,1)[res];width=320 if res==0 else 640
    words=model.initial_words(res,2 if application else phase)
    grid=grids[case['shape']];grid=[row[:] if phase==0 or application else row[::-1] for row in grid]
    ox,oy=case['origin'];foreground=(5 if res==0 else (1<<planes)-1) if application else 5&((1<<planes)-1)
    def put(x,y,value):
        for plane in range(planes):
            index=(oy+y)*width*planes//16+((ox+x)//16)*planes+plane;mask=32768>>((ox+x)%16)
            words[index]=(words[index]|mask) if value&(1<<plane) else (words[index]&~mask)
    for y,row in enumerate(grid):
        for x,value in enumerate(row):put(x,y,value)
    xmin,ymin,xmax,ymax=case['bounds'] or (0,0,18,10)
    sx,sy=case['seed'];last=1
    if xmin<=sx<=xmax and ymin<=sy<=ymax:
        last=0;target=grid[sy][sx];component={(sx,sy)};pending=deque(component)
        while pending:
            x,y=pending.popleft()
            for p in ((x-1,y),(x+1,y),(x,y-1),(x,y+1)):
                xx,yy=p
                if xmin<=xx<=xmax and ymin<=yy<=ymax and p not in component and grid[yy][xx]==target:
                    component.add(p);pending.append(p)
        _,_,rows=model.selections[case['selection']]
        for x,y in component:
            pattern=(rows[(oy+y)%len(rows)]>>(15-(ox+x)%16))&1
            value=sum(bit_rule(case['mode']-1,pattern,(target>>p)&1,(foreground>>p)&1)<<p for p in range(planes))
            put(x,y,value)
    return words,last

header=['/* Generated by src/tests/igs/generate_flood_vectors.py; see flood-vectors.json provenance. */',
        'static const char flood_grids[][11][20] = {']
for grid in grids:header.append('\t{'+','.join('"'+''.join(map(str,row))+'"' for row in grid)+'},')
header+=['};','static const struct flood_case flood_cases[] = {'];application=[]
for i,case in enumerate(cases):
    hashes=[];lasts=[]
    for phase in range(2):
        words,last=oracle(case,phase);hashes.append(digest(words));lasts.append(last)
    assert lasts[0]==lasts[1]
    res=case['resolution'];interior,index,_=model.selections[case['selection']]
    if case['app']:
        words,last=oracle(case,0,True)
        application.append(dict(resolution=res,mode=case['mode'],interior=interior,index=index,perimeter=case['perimeter'],
            origin=case['origin'],seed=case['seed'],grid=[''.join(map(str,row)) for row in grids[case['shape']]],
            text_after=case['text_after'],last_line=last,physical_runs=True,runs=runs(words,res)))
    fields=[res,case['mode'],interior,index,case['perimeter'],int(case['clipping']),lasts[0],case['shape'],*case['origin'],*case['seed']]
    bounds=case['bounds'] or (0,0,18,10)
    header.append('\t{'+','.join(map(str,fields))+',{'+','.join(map(str,bounds))+'},{UINT64_C(0x%016x),UINT64_C(0x%016x)}},'%tuple(hashes))
    if i%250==0:print(f'{i}/{len(cases)}',flush=True)
header.append('};')
models=['verify_tos104_flood.py','verify_tos104_lines.py']
provenance=dict(generator='src/tests/igs/generate_flood_vectors.py',references=['15-graphics-commands.adoc','44-native-software-lines.adoc','68-native-flood-fill.adoc','131-patterns-acceptance.adoc','137-delivery-arrays-contour-flow.adoc'],
 method='Independent static four-neighbor seed-color components and per-plane bit equations; no native run queue, SyncTERM output or Atari execution.',
 model_sha256={n:hashlib.sha256((reference/'tools'/n).read_bytes()).hexdigest() for n in models},rom_sha256=model.tables['rom_sha256'],native_cases=len(cases),
 native_initial='Outside the boxed binary grid: primary0x5aa5 XOR plane*0x1357, alternate0xa55a XOR plane*0x2468. Alternate grid mirrored horizontally to test independent topology.',
 native_foreground='Retained logical fill pen7: physical5 masked to active depth',application_foreground='Wire C2,7: physical5 low, active mask medium/mono; grid boundaries physical1 from C2,2.',
 bounds='Stored bounds apply even with clipping disabled. Ordinary boxed grids isolate exactly the source component. Out-of-bound seeds retain last state; accepted seeds clear it. Perimeter ignored.')
root=Path(__file__).resolve().parents[2]
(root/'terminal/cterm/tests/data/igs_flood_vectors.h').write_text('\n'.join(header)+'\n')
encoded=json.dumps(dict(provenance=provenance,user=model.user,cases=application),indent=2)
encoded=re.sub(r'\[\s*(-?\d+(?:,\s*-?\d+)*)\s*\]',lambda m:'['+', '.join(re.findall(r'-?\d+',m.group(1)))+']',encoded)
(Path(__file__).parent/'flood-vectors.json').write_text(encoded+'\n')
print(f'Wrote {len(cases)} native frames and {len(application)} application cases.',flush=True)
