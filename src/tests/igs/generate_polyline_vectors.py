import hashlib
import itertools
import json
import sys
from pathlib import Path

reference = Path(sys.argv[1]).resolve()
sys.path.insert(0, str(reference / 'tools'))
from verify_tos104_arrows import fixture, pixel_oracle
from verify_tos104_wide import pixels, shaft_ops
from verify_tos104_gdp import SCREEN

root = Path(__file__).resolve().parents[2]
cases = []


def add(resolution, points, style=1, width=1, caps=(0, 0), mode=1, clip=True, app=False, last=True):
    w, h = (320 if resolution == 0 else 640), (400 if resolution == 2 else 200)
    bounds = (0, 0, w-1, h-1) if clip is True or clip is False else clip
    cases.append(dict(resolution=resolution, points=points, style=style, width=width,
                      caps=caps, mode=mode, clipping=clip is not False, bounds=bounds, app=app,last=last))


shapes = [((40,60),(80,60),(80,90)),
          ((40,40),(41,40),(43,40),(85,65),(84,64)),
          ((40,40),(75,65),(45,85),(40,40)),
          ((60,60),(60,60),(60,60)),
          ((40,60),(80,60),(40,60),(40,61))]
for res, style, mode, points in itertools.product(range(3),range(1,8),range(1,5),shapes):
    add(res,points,style=style,mode=mode)
for res, width, begin, end, mode, points in itertools.product(range(3),(3,9,39),range(3),range(3),range(1,5),shapes[:3]):
    add(res,points,width=width,caps=(begin,end),mode=mode)
for res, mode, caps, points in itertools.product(range(3),range(1,5),((1,0),(0,1),(1,1)),shapes[1:]):
    add(res,points,style=7,caps=caps,mode=mode)
for res, mode, width in itertools.product(range(3),range(1,5),(1,3,9)):
    for clipping in (False,(48,45,82,76)):
        add(res,shapes[1],width=width,caps=(1,1),mode=mode,clip=clipping)
    add(res,((40,65),(105,95),(40,65),(40,65)),width=width,caps=(2,0),mode=mode,last=width == 1)
for res, mode in itertools.product(range(3),range(1,5)):
    add(res,shapes[0],style=mode+1,mode=mode,app=True)
    add(res,shapes[1],width=9,caps=(1,1),mode=mode,app=True)
    add(res,shapes[2],width=3,caps=(2,2),mode=mode,app=True)
    add(res,shapes[1],style=7,caps=(1,1),mode=mode)


def digest(words):
    result = 14695981039346656037
    for word in words:
        for byte in (word >> 8, word & 255):
            result = ((result ^ byte)*1099511628211) & 0xffffffffffffffff
    return result


def runs(words, width, height, planes):
    result = []
    for y in range(height):
        row = []
        for x in range(width):
            offset = y*(width*planes//16) + (x//16)*planes
            row.append(sum(((words[offset+p]>>(15-x%16))&1)<<p for p in range(planes)))
        start = 0
        while start < width:
            end = start+1
            while end < width and row[end] == row[start]: end += 1
            if row[start]: result.append((y,start,end-start,row[start]))
            start = end
    return result


header = ['/* Generated by src/tests/igs/generate_polyline_vectors.py; see polyline-vectors.json provenance. */',
          'static const struct polyline_case polyline_cases[] = {']
application = []
for index, case in enumerate(cases):
    res = case['resolution']; planes = (4,2,1)[res]
    hashes = []
    for seed in (0,65535):
        b, _, _, _ = fixture(case['points'],width=case['width'],caps=case['caps'],planes=planes,
                             mode=case['mode']-1,clip=case['bounds'] if case['clipping'] else None)
        # Full native capacity, including all edges; oracle inputs are explicit.
        b.words.update({SCREEN+offset:seed for offset in range(0,32000,2)})
        b.words[0x3baa+164] = 0xa531
        bounds = case['bounds'] if case['clipping'] else None
        if case['last']:
            out, _, _ = pixel_oracle(b,case['points'],case['width'],case['caps'],planes,
                                     case['mode']-1,case['style']-1,bounds)
        else:
            assert not any(c & 1 for c in case['caps'])
            ops = shaft_ops(case['points'],case['width'],b.backing(0x282e),b.backing(0x2830),case['caps'])
            out, _ = pixels(b,ops,planes=planes,mode=case['mode']-1,clip=bounds,initial_last=0)
        words = [out[SCREEN+offset] for offset in range(0,32000,2)]
        hashes.append(digest(words))
        if seed == 0 and case['app']:
            app = dict(case); app['runs'] = runs(words,320 if res == 0 else 640,400 if res == 2 else 200,planes)
            application.append(app)
    numbers = [res,case['style'],case['width'],*case['caps'],case['mode'],int(case['clipping']),int(case['last']),len(case['points'])]
    coordinates = sum((list(p) for p in case['points']),[])
    header.append('\t{' + ','.join(map(str,numbers)) + ',{' + ','.join(map(str,coordinates)) + '},{' +
                  ','.join(map(str,case['bounds'])) + '},{UINT64_C(0x%016x),UINT64_C(0x%016x)}},'%tuple(hashes))
    if index % 250 == 0: print(f'{index}/{len(cases)}',flush=True)
header.append('};')
models = ['verify_tos104_arrows.py','verify_tos104_wide.py','verify_tos104_gdp.py',
          'verify_tos104_polygon.py','verify_tos104_lines.py','verify_tos104_line_clip.py']
provenance = dict(generator='src/tests/igs/generate_polyline_vectors.py',
    references=['43-native-line-clipping.adoc','44-native-software-lines.adoc','46-native-polygon-fill.adoc',
                '50-native-wide-lines.adoc','51-native-arrowheads.adoc','137-delivery-arrays-contour-flow.adoc'],
    method='Independent rational/bit/circle/arrow oracles from the supplied reference tools; no SyncTERM output or Atari instruction execution.',
    model_sha256={name:hashlib.sha256((reference/'tools'/name).read_bytes()).hexdigest() for name in models},
    rom_sha256=hashlib.sha256((reference/'TOS/tos104.img').read_bytes()).hexdigest(),
    native_cases=len(cases), native_foreground='Physical 9 masked to the active depth; logical pen 10 retained across a mode change',
    native_hash='FNV-1a-64 over all 32000 big-endian native bytes, independently for initial zero/all-one planes')
(root/'terminal/cterm/tests/data/igs_polyline_vectors.h').write_text('\n'.join(header)+'\n')
(Path(__file__).parent/'polyline-vectors.json').write_text(json.dumps(dict(provenance=provenance,cases=application),indent=2)+'\n')
print(f'Wrote {len(cases)} native cases and {len(application)} application cases.',flush=True)
