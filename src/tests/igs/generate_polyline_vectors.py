"""Maintainer-only z fixtures from independent source-derived TOS oracles.

Usage: python3 src/tests/igs/generate_polyline_vectors.py /path/to/IGS
Ordinary tests use checked-in results, never the reference tree or a ROM.
No SyncTERM executable or emulator is used by this generator.
"""
