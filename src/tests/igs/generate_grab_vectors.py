import hashlib
import json
from pathlib import Path
import sys

reference = Path(sys.argv[1]).resolve()
sys.path.insert(0, str(reference / "tools"))
from spec_tos104_software_copy import SoftwareCopy
from verify_tos104_raster_forms import fixture, R, SB, DB, SM, DM


def pattern(index, bank, mask):
    return (((7*index) ^ (index >> 2) ^ 3) if bank == 0 else ((3*index) ^ (index >> 3) ^ 5)) & mask


def digest(values):
    value = 14695981039346656037
    for byte in values: value = ((value ^ byte)*1099511628211) & 0xffffffffffffffff
    return value


configurations = (
    (0, 4, 1, 1, 0, 0, 49, 3, 7, 1),
    (0, 4, 1, 1, 7, 1, 49, 3, 0, 0),
    (0, 4, 2, 2, 3, 0, 17, 3, 15, 1),
    (0, 4, 2, 2, 15, 1, 33, 3, 3, 0),
    (0, 4, 1, 1, 3, 0, 1, 3, 15, 1),
    (0, 4, 1, 1, 15, 1, 15, 3, 3, 0),
    (3, 3, 2, 1, 3, 0, 49, 3, 7, 1),
    (2, 3, 1, 2, 7, 1, 49, 3, 3, 0),
    (2, 1, 2, 1, 3, 1, 49, 3, 3, 1),
    (3, 1, 1, 2, 7, 1, 49, 3, 7, 1),
)
rows = []
for resolution, planes in enumerate((4, 2, 1)):
    mask = (1 << planes)-1
    for route, operation, sw, dw, sx, sy, width, height, dx, dy in configurations:
        for logic in range(16):
            source_bank = 1 if (route, operation) in ((2, 3), (3, 1)) else 0
            destination_bank = source_bank if operation == 4 else 1-source_bank
            points = [sx, sy, sx+width-1, sy+height-1, dx, dy, dx+width-1, dy+height-1]
            bases = (SB, DB)
            bus, forms, _ = fixture(planes=planes, source=bases[source_bank], destination=bases[destination_bank],
                                    operation=logic, points=points)
            bus.words[SM+8] = sw; bus.words[DM+8] = dw
            for bank, base in enumerate(bases):
                for group in range(32):
                    for plane in range(planes):
                        word = sum(((pattern(group*16+bit, bank, mask) >> plane) & 1) << (15-bit) for bit in range(16))
                        bus.words[base+2*(group*planes+plane)] = word

            def complete(event, prepared):
                SoftwareCopy(bus, frame=event["frame"]).execute(x_registers=event["x_registers"])

            forms.completion = complete
            list(forms.wrapper_steps(frame=R))
            hashes = []
            for base in bases:
                pixels = [sum(((bus.backing(base+2*((index//16)*planes+plane)) >> (15-index%16)) & 1) << plane
                              for plane in range(planes)) for index in range(512)]
                hashes.append(digest(pixels))
            rows.append((resolution, route, operation, sw, dw, sx, sy, width, height, dx, dy, hashes))
header = ["/* Generated by generate_grab_vectors.py; see grab-vectors.json provenance. */",
          "static const struct alias_case alias_cases[] = {"]
for *fields, hashes in rows:
    header.append("\t{" + ",".join(map(str, fields)) + ",{UINT64_C(0x%016x),UINT64_C(0x%016x)}}," % tuple(hashes))
header.append("};")
root = Path(__file__).resolve().parents[2]
(root / "terminal/cterm/tests/data/igs_grab_vectors.h").write_text("\n".join(header) + "\n")
models = ("spec_tos104_software_copy.py", "spec_tos104_raster_forms.py", "verify_tos104_raster_forms.py")
provenance = dict(generator="src/tests/igs/generate_grab_vectors.py",
                  references=["18-raster-transfer-commands.adoc", "70-native-raster-forms.adoc", "71-native-software-copy.adoc"],
                  method="Original fixed addressed software-copy data model and literal tables; no opcode execution or SyncTERM output. Compare indexed residues, including source-cache overlap and destination row aliases.",
                  checksum="FNV-1a64 over the first 512 physical indices, one byte per index, separately for memory0/1.",
                  rom_sha256=hashlib.sha256((reference / "TOS/tos104.img").read_bytes()).hexdigest(),
                  model_sha256={name: hashlib.sha256((reference / "tools" / name).read_bytes()).hexdigest() for name in models},
                  cases=len(rows))
(Path(__file__).parent / "grab-vectors.json").write_text(json.dumps(dict(provenance=provenance), indent=2) + "\n")
