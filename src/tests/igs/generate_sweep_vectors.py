import hashlib
import itertools
import json
import sys
from pathlib import Path

reference = Path(sys.argv[1]).resolve()
sys.path.insert(0,str(reference/'tools'))
from verify_tos104_arrows import fixture, effect
from verify_tos104_wide import pixels, shaft_ops
from verify_tos104_gdp import SCREEN, outline_pixels

root = Path(__file__).resolve().parents[2]
cases = []
SHAPES = ((60,40,92,90,0,48,1,11,0), (60,40,44,90,0,92,0,13,0),
          (40,60,110,92,1,44,1,13,0), (40,60,110,44,1,92,0,13,0))


def add(res,args,style=1,width=1,caps=(0,0),mode=1,clip=None,last=True,app=False):
    w,h = (320 if res == 0 else 640),(400 if res == 2 else 200)
    cases.append(dict(resolution=res,args=args,style=style,width=width,caps=caps,mode=mode,
                      bounds=clip or (0,0,w-1,h-1),clipping=True,last=last,app=app))


for res,style,mode,shape in itertools.product(range(3),range(1,8),range(1,5),range(4)):
    add(res,SHAPES[shape],style=style,mode=mode,
        app=style in (2,7) and shape == 0)
for res,width,caps,mode,shape in itertools.product(range(3),(3,9),((1,0),(0,1),(2,2)),range(1,5),range(2)):
    add(res,SHAPES[shape],style=1,width=width,caps=caps,mode=mode,
        app=width == 9 and caps == (2,2) and shape == 1)
for res,width,mode,shape in itertools.product(range(3),(1,9),range(1,5),range(4)):
    add(res,SHAPES[shape],style=3 if width==1 else 1,width=width,caps=(1,1),mode=mode,clip=(55,50,85,80))
for res,width,mode in itertools.product(range(3),(3,9),range(1,5)):
    add(res,SHAPES[0],width=width,caps=(2,2),mode=mode,last=False)


def digest(words):
    result=14695981039346656037
    for word in words:
        for byte in (word>>8,word&255):result=((result^byte)*1099511628211)&0xffffffffffffffff
    return result


def runs(words,width,height,planes):
    result=[]
    for y in range(height):
        row=[]
        for x in range(width):
            offset=(y*width+x)//16*planes
            row.append(sum(((words[offset+p]>>(15-x%16))&1)<<p for p in range(planes)))
        start=0
        while start<width:
            end=start+1
            while end<width and row[end]==row[start]:end+=1
            if row[start]:result.append((y,start,end-start,row[start]))
            start=end
    return result


header=['/* Generated by src/tests/igs/generate_sweep_vectors.py; see sweep-vectors.json provenance. */',
        'static const struct sweep_case sweep_cases[] = {']
application=[]
for number,case in enumerate(cases):
    res=case['resolution']; planes=(4,2,1)[res]
    ax,ay,fx,fy,axis,start,increasing,step,wait=case['args']
    bound=(fx,fy)[axis]; scalars=list(range(start,bound,max(1,step)*(1 if increasing else -1)))
    endpoint=[fx,fy]
    if scalars:endpoint[axis]=scalars[-1]
    hashes=[]; final_last=case['last']
    for seed in (0,65535):
        screen={SCREEN+offset:seed for offset in range(0,32000,2)}
        last=case['last']
        for scalar in scalars:
            end=[fx,fy];end[axis]=scalar; points=((ax,ay),tuple(end))
            b,_,_,_=fixture(points,width=case['width'],caps=case['caps'],planes=planes,
                             mode=case['mode']-1,clip=case['bounds'])
            b.words.update(screen); b.words[0x3baa+164]=0xa531
            triangles,modified=effect(points,case['width'],b.backing(0x282e),b.backing(0x2830),case['caps'])
            ops=[('polygon',triangle) for triangle in triangles]
            if case['width']==1:
                out,_=outline_pixels(b,points,planes=planes,mode=case['mode']-1,index=case['style']-1,clip=case['bounds'])
                # The thin primitive sets final-segment ownership on entry;
                # arrows follow it and may change polygon last-line state.
                class Initial:
                    words=out
                    def backing(self,address):return b.backing(address)
                out,last=pixels(Initial(),ops,planes=planes,mode=case['mode']-1,clip=case['bounds'],initial_last=1)
            else:
                ops+=shaft_ops(modified,case['width'],b.backing(0x282e),b.backing(0x2830),case['caps'])
                out,last=pixels(b,ops,planes=planes,mode=case['mode']-1,clip=case['bounds'],initial_last=last)
            screen={address:out[address] for address in screen}
        words=[screen[SCREEN+offset] for offset in range(0,32000,2)]
        hashes.append(digest(words)); final_last=last
        if seed==0 and case['app']:
            scene=dict(case,points=((ax,ay),tuple(endpoint)),scalars=scalars,
                       runs=runs(words,320 if res==0 else 640,400 if res==2 else 200,planes))
            application.append(scene)
    numbers=[res,case['style'],case['width'],*case['caps'],case['mode'],int(case['clipping']),int(case['last'])]
    header.append('\t{'+','.join(map(str,numbers))+',{'+','.join(map(str,case['args']))+'},{'+
                  ','.join(map(str,case['bounds']))+'},{'+','.join(map(str,(ax,ay,*endpoint)))+'},'+str(int(final_last))+',{' +
                  ','.join('UINT64_C(0x%016x)'%h for h in hashes)+'}},')
    if number%50==0:print(f'{number}/{len(cases)}',flush=True)
header.append('};')
models=['verify_tos104_arrows.py','verify_tos104_wide.py','verify_tos104_gdp.py',
        'verify_tos104_polygon.py','verify_tos104_lines.py','verify_tos104_line_clip.py']
provenance=dict(generator='src/tests/igs/generate_sweep_vectors.py',
    references=['19-extended-math-sweeps.adoc','43-native-line-clipping.adoc','44-native-software-lines.adoc',
                '46-native-polygon-fill.adoc','50-native-wide-lines.adoc','51-native-arrowheads.adoc'],
    method='Compose separate two-point primitives using independent rational/bit/circle/arrow oracles, carrying the explicitly seeded native screen and last-line state. Python ranges specify the exclusive monotonic sweep; no SyncTERM output or Atari instruction execution.',
    model_sha256={name:hashlib.sha256((reference/'tools'/name).read_bytes()).hexdigest() for name in models},
    rom_sha256=hashlib.sha256((reference/'TOS/tos104.img').read_bytes()).hexdigest(),
    native_cases=len(cases),application_cases=len(application),
    native_foreground='Physical 9 masked to active depth; logical pen 10 retained across a mode change',
    native_hash='FNV-1a-64 over all 32000 big-endian native bytes, separately for zero/all-one initial planes')
(root/'terminal/cterm/tests/data/igs_sweep_vectors.h').write_text('\n'.join(header)+'\n')
(Path(__file__).parent/'sweep-vectors.json').write_text(json.dumps(dict(provenance=provenance,cases=application),indent=2)+'\n')
print(f'Wrote {len(cases)} native and {len(application)} application cases.',flush=True)
