import argparse
import hashlib
import json
from pathlib import Path
import random
import sys


def generate(root):
    sys.dont_write_bytecode = True
    sys.path.insert(0, str(root/'tools'))
    from spec_igs_note_commands import Context, PATCHES
    explicit = json.loads((root/'docs/igs/note-command-vectors.json').read_text())
    values = [row['values'] for row in explicit['cases'] if row.get('command') == 'n']
    base = [2, 1, 10, 60, 0, 0]
    boundaries = [-32768, -1, 0, 1, 2, 3, 4, 15, 16, 19, 20, 124, 125, 126, 254, 255, 256, 32767]
    for field in range(6):
        for word in boundaries:
            row = base[:]; row[field] = word; values.append(row)
    for effect in range(20):
        row = base[:]; row[0] = effect; values.append(row)
    rng = random.Random(0x4947534e)
    values += [[rng.randrange(-32768, 32768) for _ in range(6)] for _ in range(100)]
    rows = []
    for v in values:
        ctx = Context(clocks=(0, 65535), key_status=(0,))
        events = list(ctx.note(v))
        normalized = ctx.note_frames[-1].read_words(8, 6)
        on = [e for e in events if e['call'] == 'gist_snd_on']
        actions = [[1 if e['call'] == 'gist_release' else 2, e['arguments'][0]]
                   for e in events if e['call'] in ('gist_release', 'gist_stop')]
        rows.append(dict(values=v, normalized=normalized,
                         patch=PATCHES.index(on[0]['arguments'][0]) if on else -1,
                         actions=actions))
    lines = ['/* Independent n normalization/call fixtures; generated by generate_note_vectors.py. */',
             'static const struct note_case note_cases[] = {']
    for row in rows:
        actions = row['actions']+[[0, 0]]*(3-len(row['actions']))
        arrays = ['{'+','.join(map(str, row[name]))+'}' for name in ('values', 'normalized')]
        action_text = '{'+','.join('{'+','.join(map(str, a))+'}' for a in actions)+'}'
        lines.append('\t{'+','.join([*arrays, str(row['patch']), str(len(row['actions'])), action_text])+'},')
    lines.append('};')
    paths = {str(Path(m.__file__).relative_to(root)): hashlib.sha256(Path(m.__file__).read_bytes()).hexdigest()
             for name, m in sys.modules.items() if name.startswith('spec_igs_') and getattr(m, '__file__', None)}
    path = 'docs/igs/note-command-vectors.json'
    paths[path] = hashlib.sha256((root/path).read_bytes()).hexdigest()
    metadata = dict(generator='src/tests/igs/generate_note_vectors.py',
                    references=['23-note-music-commands.adoc', '06-audio.adoc', '57-gist-caller-apis.adoc'],
                    source_sha256=dict(sorted(paths.items())), cases=len(rows), seed='0x4947534e',
                    method='Seven explicit n rows, six fields at 18 signed-word boundaries, all original effects and 100 stable random requests. Independent Context.note emits normalized callee words and GIST call actions; no Atari execution or SyncTERM output.',
                    timing_policy='Local monotonic deadlines at 200 units/second. Correct the native low-word wrap early exit; do not reproduce foreign clock/interrupt/bus timing. Any one key ends the delay and still performs stop. Zero delay samples the start but does not suspend/poll a key.')
    return '\n'.join(lines)+'\n', json.dumps(metadata, indent=2)+'\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('reference', type=Path)
    parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    header, metadata = generate(args.reference.resolve())
    for path, text in ((root/'terminal/cterm/tests/data/igs_note_vectors.h', header),
                       (Path(__file__).with_name('note-vectors.json'), metadata)):
        if args.check:
            assert path.read_text() == text, path
        else:
            path.write_text(text)
