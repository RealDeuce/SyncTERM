import hashlib
import itertools
import json
from pathlib import Path
import re
import sys
from text_oracle import NativeText,checksum
from filled_curve_oracle import runs
reference=Path(sys.argv[1]).resolve();model=NativeText(reference)
cases=[];texts=[];text_ids={}
def text_id(data):
    data=bytes(data)
    if data not in text_ids:text_ids[data]=len(texts);texts.append(data)
    return text_ids[data]
def add(res,mode,point,style,rotation,origin=(100,100),clip=True,bounds=None,last=True,align=(0,0),
        text=b'A\x80\xff',payload=None,direct=False,app=False,text_after=False,tag=''):
    payload=text if payload is None else payload
    collected=bytes(x for x in payload if x not in (10,13)) or b'@'
    cases.append(dict(resolution=res,mode=mode,points=point,style=style,rotation=rotation,origin=origin,
        clipping=clip,bounds=bounds,last=bool(last),align=align,text=list(text),text_id=text_id(text),wire_id=text_id(payload),
        collected=list(collected),direct=direct,app=app,text_after=text_after,tag=tag))
points=(8,9,10,16,18,20)
for res,mode,point,style,rotation in itertools.product(range(3),range(1,5),points,range(32),range(4)):
    app=style in (0,31) and mode==1+(points.index(point)+rotation+int(style==31))%4
    add(res,mode,point,style,rotation,last=(style+mode)%2,app=app)
for res,mode,point,style,rotation,bounds in itertools.product(range(3),range(1,5),points,(1,2,4,16,31),range(4),
        ((96,92,110,107),(100,100,100,100),(110,110,90,90))):
    add(res,mode,point,style,rotation,bounds=bounds,last=False)
for res,mode,point,style,rotation,corner in itertools.product(range(3),range(1,5),points,(1,4,31),range(4),range(4)):
    width=320 if res==0 else 640;height=400 if res==2 else 200
    add(res,mode,point,style,rotation,origin=((width-1 if corner&1 else 0),(height-1 if corner&2 else 0)),last=False)
for res,mode,point,style,rotation,corner in itertools.product(range(3),range(1,5),(9,20),(1,4,31),range(4),range(4)):
    width=320 if res==0 else 640;height=400 if res==2 else 200
    add(res,mode,point,style,rotation,origin=((width-1 if corner&1 else 0),(height-1 if corner&2 else 0)),clip=False,last=False)
for point,character in itertools.product(points[:3],range(256)):
    add(0,1,point,0,0,text=bytes([character]),direct=True)
for res,mode,point,style in itertools.product(range(3),range(1,5),points,range(32)):
    add(res,mode,point,style,4,last=False)
for res,mode,point,style,rotation in itertools.product(range(3),(1,3),points,(0,31),(-1,-2,-3,-4,-37,-32768)):
    add(res,mode,point,style,rotation,last=False)
for point,style,rotation,h,v in itertools.product(points,(5,31),range(4),range(3),range(6)):
    add(0,1,point,style,rotation,align=(h,v),last=False)
for res,mode,point in itertools.product(range(3),range(1,5),(9,20)):
    add(res,mode,point,31,0,origin=(90,18*(16 if res==2 else 8)+3),last=False,app=True,text_after=True)
for res in range(3):
    specials=[('empty',b'@',b''),('crlf',b'A\x80\xff',b'A\r\n\x80\xff'),('nul',b'A',b'A\0\x80\xff'),
              ('opaque',b'\x1b[31mG#M>4:\x80\xff',b'\x1b[31mG#M>4:\x80\xff'),('limit',b'X'*128,b'X'*128)]
    for tag,text,payload in specials:add(res,3,9,0,0,text=text,payload=payload,app=True,tag=tag)
    add(res,1,9,31,4,app=True,tag='full-turn')

header=['/* Generated by generate_text_vectors.py; see text-vectors.json provenance. */',
        'static const struct text_string text_strings[] = {']
for value in texts:header.append('\t{'+str(len(value))+',{'+(','.join(map(str,value)) if value else '0')+'}},')
header+=['};','static const struct text_case text_cases[] = {'];application=[]
for i,c in enumerate(cases):
    hashes=[checksum(model.frame(c,phase)) for phase in range(2)]
    bounds=c['bounds'] or (0,0,319 if c['resolution']==0 else 639,399 if c['resolution']==2 else 199)
    fields=[c['resolution'],c['mode'],c['points'],c['style'],c['rotation'],*c['origin'],int(c['clipping']),int(c['last']),*c['align'],int(c['direct']),c['text_id'],c['wire_id']]
    header.append('\t{'+','.join(map(str,fields))+',{'+','.join(map(str,bounds))+'},{UINT64_C(0x%016x),UINT64_C(0x%016x)}},'%tuple(hashes))
    if c['app']:
        frame=model.frame(c,0,True)
        application.append(dict(resolution=c['resolution'],mode=c['mode'],points=c['points'],style=c['style'],rotation=c['rotation'],
            origin=c['origin'],text=c['text'],payload=list(texts[c['wire_id']]),collected_size=len(c['collected']),
            last_line=int(c['last']),text_after=c['text_after'],tag=c['tag'],runs=runs(frame,c['resolution'])))
    if i%250==0:print(f'{i}/{len(cases)}',flush=True)
header.append('};')
models=['oracle_delivery_text_effects.py','verify_delivery_text_effects.py','verify_tos104_lines.py','verify_tos104_line_clip.py']
provenance=dict(generator='src/tests/igs/generate_text_vectors.py',oracle='src/tests/igs/text_oracle.py',
    references=['04-text-console.adoc','30-native-font-sizing.adoc','33-native-text-layout.adoc','34-native-fast-text.adoc',
                '35-native-text-scratch.adoc','36-native-text-raster.adoc','37-native-text-effects.adoc','38-native-software-text.adoc',
                '43-native-line-clipping.adoc','44-native-software-lines.adoc','139-delivery-text-callers.adoc','140-delivery-shared-text-readers.adoc','144-text-acceptance.adoc'],
    method='Independent original-font array resampling/dilation/skew/outline/rotation/clip oracle, separately validated against native addressed software text; independent line positions and Boolean bits for underline. No SyncTERM output or Atari execution.',
    adaptations='Bind the glyph fixture foreground to the requested physical index; discard writes outside the host canvas; reject inverted/cyclic invalid clips. Preserve glyph geometry and native effects. Correct unsupported E angles by safe periodic projection.',
    checksum='CRC32 in high32 bits, Adler32 in low32 bits, over all32000 native big-endian bytes',
    model_sha256={n:hashlib.sha256((reference/'tools'/n).read_bytes()).hexdigest() for n in models},
    fonts_sha256=hashlib.sha256((reference/'docs/igs/generated/tos104-fonts.json').read_bytes()).hexdigest(),
    rom_sha256=hashlib.sha256((reference/'TOS/tos104.img').read_bytes()).hexdigest(),native_cases=len(cases),application_cases=len(application),
    native_initial='Primary0x5aa5 XOR plane*0x1357; alternate0xa55a XOR plane*0x2468. Logical text pen7 retained: physical5 masked to depth.',
    application_initial='Zero scene with literal native console Z before text, or a full console-cell replacement afterward. Wire C3,7 foreground is5 low and active mask medium/mono; runs describe the entire final scene.',
    original_glyphs=768,direct_asset_cases=768,corrected_angle_cases=sum(c['rotation']<0 or c['rotation']==4 for c in cases),
    replacement_cases=sum(c['text_after'] for c in cases if c['app']))
root=Path(__file__).resolve().parents[2]
(root/'terminal/cterm/tests/data/igs_text_vectors.h').write_text('\n'.join(header)+'\n')
encoded=json.dumps(dict(provenance=provenance,cases=application),indent=2)
encoded=re.sub(r'\[\s*(-?\d+(?:,\s*-?\d+)*)\s*\]',lambda m:'['+', '.join(re.findall(r'-?\d+',m.group(1)))+']',encoded)
(Path(__file__).parent/'text-vectors.json').write_text(encoded+'\n')
print(f'Wrote {len(cases)} native and {len(application)} application cases.',flush=True)
