#include "io_error.h"

#define WIN32_LEAN_AND_MEAN
#include <windows.h>

int
io_error_from_windows(unsigned long error)
{
	switch ((DWORD)error) {
	case ERROR_SUCCESS: return 0;
	case ERROR_INVALID_PARAMETER:
	case ERROR_INVALID_HANDLE:
	case ERROR_INVALID_NAME:
	case ERROR_BAD_PATHNAME: return IO_ERROR_INVALID_ARGUMENT;
	case ERROR_NO_UNICODE_TRANSLATION: return IO_ERROR_INVALID_ENCODING;
	case ERROR_FILE_NOT_FOUND:
	case ERROR_PATH_NOT_FOUND:
	case ERROR_INVALID_DRIVE:
	case ERROR_DEV_NOT_EXIST: return IO_ERROR_NOT_FOUND;
	case ERROR_ACCESS_DENIED:
	case ERROR_PRIVILEGE_NOT_HELD: return IO_ERROR_PERMISSION_DENIED;
	case ERROR_FILE_EXISTS:
	case ERROR_ALREADY_EXISTS: return IO_ERROR_ALREADY_EXISTS;
	case ERROR_DIRECTORY: return IO_ERROR_NOT_DIRECTORY;
	case ERROR_DIR_NOT_EMPTY: return IO_ERROR_DIRECTORY_NOT_EMPTY;
	case ERROR_NOT_ENOUGH_MEMORY:
	case ERROR_OUTOFMEMORY:
	case ERROR_COMMITMENT_LIMIT: return IO_ERROR_OUT_OF_MEMORY;
	case ERROR_DISK_FULL:
	case ERROR_HANDLE_DISK_FULL: return IO_ERROR_NO_SPACE;
	case ERROR_FILENAME_EXCED_RANGE:
	case ERROR_BUFFER_OVERFLOW: return IO_ERROR_NAME_TOO_LONG;
	case ERROR_ARITHMETIC_OVERFLOW:
	case ERROR_NEGATIVE_SEEK: return IO_ERROR_OUT_OF_RANGE;
	case ERROR_BUSY:
	case ERROR_LOCK_VIOLATION:
	case ERROR_SHARING_VIOLATION: return IO_ERROR_BUSY;
	case ERROR_WRITE_PROTECT: return IO_ERROR_READ_ONLY;
	case ERROR_NOT_SAME_DEVICE: return IO_ERROR_CROSS_DEVICE;
#ifdef ERROR_TOO_MANY_LINKS
	case ERROR_TOO_MANY_LINKS: return IO_ERROR_TOO_MANY_LINKS;
#endif
	case ERROR_OPERATION_ABORTED: return IO_ERROR_CANCELLED;
	case ERROR_SEM_TIMEOUT: return IO_ERROR_TIMED_OUT;
	case ERROR_NOT_SUPPORTED:
	case ERROR_CALL_NOT_IMPLEMENTED: return IO_ERROR_NOT_SUPPORTED;
	default: return IO_ERROR_IO;
	}
}
