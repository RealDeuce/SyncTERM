import argparse
import gzip
import hashlib
import pathlib
import sys
import urllib.request

from box_drawing import match_cp437


UNIFONT_VERSION = "18.0.01"
SOURCES = {
    "unifont": (
        f"https://www.unifoundry.com/pub/unifont/unifont-{UNIFONT_VERSION}/"
        f"font-builds/unifont-{UNIFONT_VERSION}.hex.gz",
        "e66385c79a0b8b24a466f3129930e08a966a935b4bf3b28c6bb17a9df9bf791d",
        f"unifont-{UNIFONT_VERSION}.hex.gz",
    ),
    "unscii16": (
        "https://raw.githubusercontent.com/viznut/unscii/"
        "257b4dfeb50651510fe8b9cf4f151a148a4490e4/"
        "fontfiles/unscii-16.hex",
        "2642c8b748fa81f24d76772d70c55faa720d98fadfec8133daf89136c5c8bfb1",
        "unscii-16.hex",
    ),
    "unscii8": (
        "https://raw.githubusercontent.com/viznut/unscii/"
        "257b4dfeb50651510fe8b9cf4f151a148a4490e4/"
        "fontfiles/unscii-8.hex",
        "03094f7fbab7085cf6a6b624cee61e47e71ce5d0c2f308c2f4436afdc17f776c",
        "unscii-8.hex",
    ),
}


def source_bytes(name, source_dir):
    url, expected, filename = SOURCES[name]
    if source_dir is None:
        with urllib.request.urlopen(url) as response:
            data = response.read()
    else:
        data = (source_dir / filename).read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != expected:
        raise ValueError(f"{filename}: expected SHA-256 {expected}, got {actual}")
    return gzip.decompress(data) if filename.endswith(".gz") else data


def parse_hex(data, height, name):
    result = {}
    for line_number, raw in enumerate(data.decode("ascii").splitlines(), 1):
        if not raw:
            continue
        try:
            code, encoded = raw.split(":", 1)
            codepoint = int(code, 16)
            bitmap = bytes.fromhex(encoded)
        except ValueError as error:
            raise ValueError(f"{name}:{line_number}: malformed line") from error
        if codepoint > 0x10FFFF or 0xD800 <= codepoint <= 0xDFFF:
            raise ValueError(f"{name}:{line_number}: invalid Unicode scalar")
        if height == 8 and codepoint == 0 and not any(bitmap):
            bitmap = bytes(8)
        if len(bitmap) not in (height, height * 2):
            raise ValueError(
                f"{name}:{line_number}: expected 8- or 16-pixel glyph")
        if codepoint in result:
            raise ValueError(f"{name}:{line_number}: duplicate codepoint")
        result[codepoint] = bitmap
    return result


def byte_array(out, name, data):
    out.write(f"static const uint8_t {name}[] = {{\n")
    for offset in range(0, len(data), 12):
        chunk = data[offset:offset + 12]
        out.write("\t" + ", ".join(f"0x{value:02x}" for value in chunk)
                  + ",\n")
    out.write("};\n\n")


def write_font(path, symbol, glyphs, height, notice, header, spdx=None):
    narrow = []
    wide = []
    locations = {}
    for codepoint in sorted(glyphs):
        bitmap = glyphs[codepoint]
        if len(bitmap) == height:
            locations[codepoint] = len(narrow)
            narrow.append(bitmap)
        else:
            locations[codepoint] = ("wide", len(wide))
            wide.append(bitmap)
    fallback = next((codepoint for codepoint in (0xFFFD, ord("?"))
                     if codepoint in glyphs
                     and len(glyphs[codepoint]) == height), None)
    if fallback is None:
        raise ValueError(f"{symbol}: no narrow replacement glyph")
    fallback_location = locations[fallback]
    fallback_glyph = fallback_location
    if 0xFFFD in glyphs and len(glyphs[0xFFFD]) == height * 2:
        wide_fallback_glyph = len(narrow) + locations[0xFFFD][1]
    else:
        wide_fallback_glyph = len(narrow) + len(wide)
        fallback_bitmap = glyphs[fallback]
        wide.append(b"".join((value << 4).to_bytes(2, "big")
                             for value in fallback_bitmap))
    with path.open("w", encoding="ascii", newline="\n") as out:
        out.write("/* Generated by fonts/update_fonts.py; do not edit. */\n")
        out.write(f"/* {notice} */\n\n")
        out.write("/* CP437-compatible box drawing: Copyright (c) 2026 Stephen Hurd; BSD-2-Clause. */\n\n")
        if spdx is not None:
            out.write(f"/* SPDX-License-Identifier: {spdx} */\n\n")
        out.write(f'#include "{header}"\n\n#include <stdint.h>\n\n')
        byte_array(out, f"{symbol}_narrow", b"".join(narrow))
        if wide:
            byte_array(out, f"{symbol}_wide", b"".join(wide))
        out.write(f"static const struct st_console_font_mapping "
                  f"{symbol}_mapping[] = {{\n")
        for codepoint in sorted(glyphs):
            location = locations[codepoint]
            glyph = (len(narrow) + location[1]
                     if isinstance(location, tuple) else location)
            out.write(f"\t{{UINT32_C(0x{codepoint:x}), UINT32_C({glyph})}},\n")
        out.write("};\n\n")
        out.write(f"const struct st_console_font {symbol} = {{\n")
        out.write(f"\t.bitmap = {symbol}_narrow,\n")
        out.write(f"\t.bitmap_size = sizeof({symbol}_narrow),\n")
        out.write("\t.width = 8,\n")
        out.write(f"\t.height = {height},\n")
        out.write(f"\t.glyph_count = {len(narrow)},\n")
        out.write("\t.row_stride = 1,\n")
        out.write(f"\t.glyph_stride = {height},\n")
        if wide:
            out.write(f"\t.wide_bitmap = {symbol}_wide,\n")
            out.write(f"\t.wide_bitmap_size = sizeof({symbol}_wide),\n")
            out.write(f"\t.wide_glyph_count = {len(wide)},\n")
            out.write("\t.wide_row_stride = 2,\n")
            out.write(f"\t.wide_glyph_stride = {height * 2},\n")
        out.write(f"\t.mapping = {symbol}_mapping,\n")
        out.write(f"\t.mapping_count = {len(glyphs)},\n")
        out.write(f"\t.fallback_glyph = {fallback_glyph},\n")
        out.write(f"\t.wide_fallback_glyph = {wide_fallback_glyph},\n")
        out.write("};\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source-dir", type=pathlib.Path)
    parser.add_argument("--root", type=pathlib.Path,
                        default=pathlib.Path(__file__).resolve().parents[3])
    args = parser.parse_args()
    unscii8 = parse_hex(source_bytes("unscii8", args.source_dir), 8,
                        "unscii-8.hex")
    unscii16 = parse_hex(source_bytes("unscii16", args.source_dir), 16,
                         "unscii-16.hex")
    unifont = parse_hex(source_bytes("unifont", args.source_dir), 16,
                        f"unifont-{UNIFONT_VERSION}.hex")
    match_cp437(unscii8, args.root, 8)
    match_cp437(unscii16, args.root, 16)
    composite = dict(unifont)
    composite.update(unscii16)
    generated = args.root / "src/media/fonts" / "generated"
    generated.mkdir(parents=True, exist_ok=True)
    write_font(generated / "st_unscii_8.c", "st_unscii_8_font", unscii8, 8,
               "UNSCII data: public domain / CC0; see src/media/fonts/UPSTREAM.md",
               "st_unicode_fonts.h")
    write_font(generated / "st_unscii_16.c", "st_unscii_16_font", unscii16,
               16, "UNSCII data: public domain / CC0; see src/media/fonts/UPSTREAM.md",
               "st_unicode_fonts.h")
    generated = args.root / "src/media/unifont" / "generated"
    generated.mkdir(parents=True, exist_ok=True)
    write_font(generated / "st_unifont_data.c", "st_unifont_font",
               composite, 16,
               f"SyncTERM Unicode: GNU Unifont {UNIFONT_VERSION} modified in 2026 with an "
               "UNSCII overlay; see src/media/unifont/LICENSE.OFL-1.1",
               "st_unifont.h", "OFL-1.1")

    # Keep picker names, variants and actual glyph coverage in step.
    import runpy
    catalog_dir = args.root / "src/text/emoji"
    sys.path.insert(0, str(catalog_dir))
    try:
        runpy.run_path(str(catalog_dir / "update_emoji_catalog.py"))["validate_repository"](args.root)
    finally:
        sys.path.pop(0)


if __name__ == "__main__":
    main()
