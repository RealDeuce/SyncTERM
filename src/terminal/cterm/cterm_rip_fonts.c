const uint8_t *
cterm_rip_font_data(int number, size_t *size)
{
	if (size == NULL || number < 0 || number >= 11)
		return NULL;
	return st_bgi_font_data((unsigned)number,size);
}

const uint8_t *
cterm_rip_text_font_data(int style, size_t *size)
{
	if (size == NULL)
		return NULL;
	switch (style) {
	case 1: *size = sizeof(ripfnt7x8); return ripfnt7x8;
	case 3: *size = sizeof(ripfnt7x14); return ripfnt7x14;
	case 4: *size = sizeof(ripfnt16x14); return ripfnt16x14;
	default: return NULL;
	}
}

const struct cterm_rip_font_metric *
cterm_rip_font_button_metric(int number, int size)
{
	if (number < 0 || number >= 11 || size < 1 || size > 10)
		return NULL;
	return &button_metrics[number][size - 1];
}

bool
cterm_rip_button_char_descends(uint8_t ch)
{
	return low_char[ch] != 0;
}
