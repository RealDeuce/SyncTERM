extern bool st_rip3_bitmap_error_ui_test_fail_allocate;

#define CHECK(expression) do { \
	if (!(expression)) { \
		fprintf(stderr,"check failed at line %d: %s\n",__LINE__,#expression); \
		return 1; \
	} \
} while (0)

/* Independent authored 3x3 outline glyphs; space is blank. Text layout and
 * clipping expectations are literal rasters, not generated by the renderer. */
static const char *const default_rows[] = {
	"#################################################",
	"#................................................",
	"#................................................",
	"#..##################...############...##########",
	"#..#.##.##.##.##.##.#...#.##.##.##.#...#.##.##.##",
	"#..##################...############...##########",
	"#................................................",
	"#..###############...............................",
	"#..#.##.##.##.##.#...............................",
	"#..###############...............................",
	"#................................................",
	"#................................................",
	"#################################################",
};

struct fixture {
	struct st_rip3_command_host host;
	struct st_rip3_bitmap_error_ui ui;
	struct st_rip3_resource_paths paths;
	struct st_rip3_bitmap_error_sink sink;
	uint8_t glyphs[255*3];
	struct st_rip3_maf_font font;
	unsigned errors;
	enum st_rip3_command_diagnostic kind;
};

static void
diagnostic(void *context, enum st_rip3_command_diagnostic kind)
{
	struct fixture *f = context;
	f->errors++; f->kind = kind;
}

static int
create(struct fixture *f, enum st_rip3_canvas canvas, uint32_t width, uint32_t height)
{
	const struct st_rip3_rect bounds = {10,20,61,40}, viewport = {2,1,49,18}, disabled = {0,0,0,0};
	uint32_t colors[256];
	CHECK(st_rip3_ports_create(&f->host.ports,canvas) == 0 && st_rip3_palettes_create(&f->host.palettes) == 0
	    && st_rip3_environments_create(&f->host.environments,canvas) == 0);
	CHECK(st_rip3_ports_define(f->host.ports,1,&bounds,false) == 0 && st_rip3_ports_switch(f->host.ports,1) == 0
	    && st_rip3_ports_viewport(f->host.ports,&viewport) == 0 && st_rip3_ports_erase(f->host.ports,85) == 0
	    && rip3_test_image_area(f->host.ports,1,&disabled,15) == 0 && st_rip3_ports_protect(f->host.ports,1,true) == 0);
	for (unsigned i = 0; i < 256; i++) colors[i] = i*UINT32_C(0x010101);
	CHECK(st_rip3_palettes_switch(f->host.palettes,1) == 0 && st_rip3_palettes_rgb(f->host.palettes,0,8,colors,256) == 0
	    && st_rip3_palettes_protect(f->host.palettes,1,true) == 0);
	struct st_rip3_environment environment;
	CHECK(st_rip3_environments_get(f->host.environments,0,&environment) == 0);
	environment.world_width = width; environment.world_height = height; environment.port = 9; environment.palette = 7;
	CHECK(st_rip3_environments_set(f->host.environments,0,&environment) == 0);
	for (size_t i = 0; i < 255; i++) { f->glyphs[i*3] = 0xe0; f->glyphs[i*3+1] = 0xa0; f->glyphs[i*3+2] = 0xe0; }
	memset(f->glyphs+31*3,0,3);
	memset(f->glyphs+129*3,0x40,3); /* CP437 0x82: independently recognizable e-acute. */
	f->font = (struct st_rip3_maf_font){3,3,1,3,f->glyphs};
	f->ui = (struct st_rip3_bitmap_error_ui){f->host.ports,f->host.palettes,&f->font};
	f->sink = (struct st_rip3_bitmap_error_sink){&f->ui,st_rip3_bitmap_error_show};
	f->host.resources = &f->paths; f->host.bitmap_errors = &f->sink;
	return 0;
}

static int
capture(struct fixture *f, uint32_t width, uint32_t height, int scenario)
{
	struct st_rip3_palette palette;
	struct st_rip3_bitmap *image = NULL;
	CHECK(st_rip3_palettes_get(f->host.palettes,1,&palette) == 0 && st_rip3_bitmap_capture(&image,f->host.ports,0,NULL,&palette) == 0);
	for (uint32_t y = 0; y < height; y++) for (uint32_t x = 0; x < width; x++) {
		uint8_t expected = 0;
		if (x >= 12 && x <= 59 && y >= 21 && y <= 38) {
			uint32_t vx = x-12, vy = y-21; expected = 85;
			/* The box uses exclusive wire edges, followed by the full-size
			 * local marker at near+(1,1). It can extend beyond the box. */
			if (scenario == 0 && vx >= 1 && vx < 30 && vy >= 1 && vy < 13)
				expected = vx == 1 || vx == 29 || vy == 1 || vy == 12 ? 255 : 0;
			if (scenario == 0 && vx >= 2 && vy >= 2 && vy < 15)
				expected = default_rows[vy-2][vx-2] == '#' ? 255 : 0;
			if (scenario == 1 && vy < 13) expected = default_rows[vy][vx] == '#' ? 255 : 0;
			if (scenario == 2 && vx <= 27 && vy >= 4 && vy <= 16)
				expected = vx == 27 || vy == 4 || vy == 16 ? 255 : 0;
			if (scenario == 2 && vy >= 5 && vy < 18)
				expected = default_rows[vy-5][vx+1] == '#' ? 255 : 0;
			if (scenario == 3 && vy <= 10) expected = vy == 0 || vy == 10 ? 255 : 0;
		}
		CHECK(image->pixels->primary[(size_t)y*width+x] == expected);
	}
	for (unsigned i = 0; i < 256; i++) CHECK(image->palette[i] == i*UINT32_C(0x010101));
	st_rip3_bitmap_destroy(image); return 0;
}

static int
scene(enum st_rip3_canvas canvas, uint32_t width, uint32_t height)
{
	struct fixture f = {0};
	CHECK(create(&f,canvas,width,height) == 0);
	for (size_t i = 0; i < 13; i++) CHECK(strlen(default_rows[i]) == 49);
	const struct st_rip3_command_sink diagnostics = {&f,diagnostic};
	const char explicit_command[] = "1b01010U0D0000000000X.BMP";
	st_rip3_commands_process(&f.host,&diagnostics,(const uint8_t *)explicit_command,sizeof(explicit_command)-1);
	CHECK(f.errors == 1 && f.kind == ST_RIP3_COMMAND_OPERATION_FAILED && capture(&f,width,height,0) == 0);
	st_rip3_commands_process(&f.host,&diagnostics,(const uint8_t *)"3e01",4);
	struct st_rip3_environment environment;
	CHECK(st_rip3_environments_get(f.host.environments,0,&environment) == 0 && st_rip3_environments_playback_rate(f.host.environments) == 1
	    && environment.port == 9 && environment.palette == 7 && f.errors == 1);
	CHECK(st_rip3_ports_erase(f.host.ports,85) == 0);
	const char default_command[] = "1b000000000000000000X.BMP";
	st_rip3_commands_process(&f.host,&diagnostics,(const uint8_t *)default_command,sizeof(default_command)-1);
	CHECK(f.errors == 2 && capture(&f,width,height,1) == 0);
	CHECK(st_rip3_ports_erase(f.host.ports,85) == 0);
	const struct st_rip3_bitmap_destination clipped = {-2,4,27,16};
	st_rip3_bitmap_error_show(&f.ui,"X.BMP",1,&clipped,false);
	CHECK(capture(&f,width,height,2) == 0);
	CHECK(st_rip3_ports_erase(f.host.ports,85) == 0);
	const int64_t limit = INT64_C(1024)*INT32_MAX;
	const struct st_rip3_bitmap_destination wide = {-limit,0,limit,10};
	st_rip3_bitmap_error_show(&f.ui,"X.BMP",1,&wide,false);
	CHECK(capture(&f,width,height,3) == 0);
	CHECK(st_rip3_ports_erase(f.host.ports,85) == 0);
	st_rip3_bitmap_error_ui_test_fail_allocate = true;
	st_rip3_commands_process(&f.host,&diagnostics,(const uint8_t *)explicit_command,sizeof(explicit_command)-1);
	CHECK(!st_rip3_bitmap_error_ui_test_fail_allocate && f.errors == 3 && f.kind == ST_RIP3_COMMAND_OPERATION_FAILED
	    && capture(&f,width,height,-1) == 0);
	st_rip3_commands_process(&f.host,&diagnostics,(const uint8_t *)"3e02",4);
	CHECK(st_rip3_environments_get(f.host.environments,0,&environment) == 0 && st_rip3_environments_playback_rate(f.host.environments) == 2 && f.errors == 3);
	st_rip3_bitmap_error_show(&f.ui,"\xff",1,NULL,false);
	f.font.glyph_size = 4; st_rip3_bitmap_error_show(&f.ui,"X.BMP",1,NULL,false); f.font.glyph_size = 3;
	st_rip3_bitmap_error_show(&f.ui,"X.BMP",2,NULL,false);
	const struct st_rip3_bitmap_destination invalid = {5,0,4,1};
	st_rip3_bitmap_error_show(&f.ui,"X.BMP",1,&invalid,false);
	CHECK(capture(&f,width,height,-1) == 0);
	/* A UTF-8 scalar consumes one fallback glyph, rather than four bytes. */
	st_rip3_bitmap_error_show(&f.ui,"X\xf0\x9f\x99\x82",1,NULL,false);
	uint8_t pixel;
	CHECK(st_rip3_ports_read(f.host.ports,1,10,8,&pixel) == 0 && pixel == 255);
	CHECK(st_rip3_ports_read(f.host.ports,1,11,8,&pixel) == 0 && pixel == 0);
	st_rip3_bitmap_error_show(&f.ui,"\xc3\xa9",1,NULL,false);
	CHECK(st_rip3_ports_read(f.host.ports,1,5,8,&pixel) == 0 && pixel == 0);
	CHECK(st_rip3_ports_read(f.host.ports,1,6,8,&pixel) == 0 && pixel == 255);
	CHECK(st_rip3_ports_erase(f.host.ports,85) == 0);
	f.ui.font = NULL; st_rip3_bitmap_error_show(&f.ui,"X.BMP",1,NULL,false);
	unsigned native_height = width == 640 ? 11 : width == 800 ? 13 : 17;
	/* The native default box extends beyond this short viewport. Its top
	 * border paints; no invented bottom edge appears at the clipping edge. */
	CHECK(native_height*2+7 > 18);
	CHECK(st_rip3_ports_read(f.host.ports,1,49,1,&pixel) == 0 && pixel == 255);
	CHECK(st_rip3_ports_read(f.host.ports,1,3,18,&pixel) == 0 && pixel == 0);
	unsigned current; struct st_rip3_port_info info;
	CHECK(st_rip3_ports_current(f.host.ports,&current) == 0 && current == 1
	    && st_rip3_ports_info(f.host.ports,1,&info) == 0 && info.protected && !info.image.enabled && info.image.flags == 15);
	uint32_t colors[256];
	for (unsigned i = 0; i < 256; i++) colors[i] = 0x777777;
	colors[7] = 0; colors[9] = 0xffffff;
	CHECK(st_rip3_palettes_protect(f.host.palettes,1,false) == 0
	    && st_rip3_palettes_rgb(f.host.palettes,0,8,colors,256) == 0 && st_rip3_palettes_protect(f.host.palettes,1,true) == 0);
	const struct st_rip3_bitmap_destination small = {1,1,30,13};
	st_rip3_bitmap_error_show(&f.ui,"X.BMP",1,&small,false);
	CHECK(st_rip3_ports_read(f.host.ports,1,3,2,&pixel) == 0 && pixel == 9);
	CHECK(st_rip3_ports_read(f.host.ports,1,4,3,&pixel) == 0 && pixel == 9);
	CHECK(st_rip3_ports_read(f.host.ports,1,5,4,&pixel) == 0 && pixel == 7);
	struct st_rip3_palette retained;
	CHECK(st_rip3_palettes_get(f.host.palettes,1,&retained) == 0 && memcmp(retained.rgb,colors,sizeof(colors)) == 0);
	CHECK(st_rip3_ports_protect(f.host.ports,1,false) == 0 && st_rip3_ports_activate(f.host.ports,false) == 0);
	f.ui.palettes = NULL; st_rip3_bitmap_error_show(&f.ui,NULL,1,NULL,false);
	st_rip3_environments_destroy(f.host.environments); st_rip3_palettes_destroy(f.host.palettes); st_rip3_ports_destroy(f.host.ports);
	return 0;
}

int
main(void)
{
	CHECK(scene(ST_RIP3_CANVAS_640_480,640,480) == 0);
	CHECK(scene(ST_RIP3_CANVAS_800_600,800,600) == 0);
	CHECK(scene(ST_RIP3_CANVAS_1024_768,1024,768) == 0);
	return 0;
}
