int32_t st_bgi_sin32(int angle)
{
	bool negative=false;
	angle%=360;
	if (angle<0) angle+=360;
	if (angle>180) { angle-=180; negative=true; }
	if (angle>90) angle=180-angle;
	int32_t value=(int32_t)sine_quadrant[angle]*2;
	return negative?-value:value;
}
int16_t st_bgi_trig_mul(int32_t coefficient, uint16_t radius)
{
	uint32_t bits=(uint32_t)coefficient;
	uint32_t high=(bits>>16)*radius, low=(bits&65535u)*radius;
	uint16_t word=(uint16_t)(high+(low>>16));
	int32_t result=word<32768?(int32_t)word:(int32_t)word-65536;
	return (int16_t)result;
}
