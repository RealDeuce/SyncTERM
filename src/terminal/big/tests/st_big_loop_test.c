#define CHECK(x) do { if (!(x)) { fprintf(stderr,"%s:%d: %s\n",__FILE__,__LINE__,#x); return 1; } } while (0)
#define WORD(x) ((uint16_t)(x))

struct fixture {
	struct st_big_loop loop;
	struct st_big_loop_reader reader;
	struct st_big_loop_sink sink;
	unsigned delays, keys, randoms, delay_retries;
	bool hold_delay, hold_key, cancel;
	int delay_error, key_error;
	uint16_t last_delay, lower, upper;
	uint32_t rng;
};

static int
delay(void *context, uint16_t duration, bool first)
{
	struct fixture *f = context;
	if (first) CHECK(f->loop.varying_count == 0);
	else ++f->delay_retries;
	++f->delays;
	f->last_delay = duration;
	return f->delay_error != 0 ? f->delay_error : f->hold_delay ? IO_ERROR_IN_PROGRESS : 0;
}

static int
key(void *context, bool *cancel)
{
	struct fixture *f = context;
	++f->keys;
	if (f->key_error != 0) return f->key_error;
	if (f->hold_key) return IO_ERROR_IN_PROGRESS;
	*cancel = f->cancel;
	return 0;
}

static int
random_word(void *context, uint16_t *word)
{
	struct fixture *f = context;
	++f->randoms;
	size_t attempts;
	return st_big_random_range(&f->rng,f->lower,f->upper,1,&attempts,word);
}

static int
setup(struct fixture *f, int from, int to, int step, uint16_t type,
    const int *words, size_t count)
{
	memset(f,0,sizeof(*f));
	CHECK(count >= 1 && count <= ST_BIG_LOOP_CAPACITY);
	st_big_loop_init(&f->loop);
	f->loop.current = f->loop.origin = WORD(from);
	f->loop.to = WORD(to);
	f->loop.step = st_big_loop_setup_step(WORD(from),WORD(to),WORD(step));
	f->loop.type = type;
	f->loop.command = 'L';
	f->loop.count = (uint16_t)count;
	for (size_t i = 0; i < count; ++i) f->loop.words[i] = WORD(words[i]);
	CHECK(st_big_loop_publish(&f->loop) == 0);
	CHECK(st_big_loop_scan(&f->loop) == 0);
	f->rng = 1; f->upper = 199;
	f->sink = (struct st_big_loop_sink){f,delay,key,random_word};
	st_big_loop_reader_begin(&f->reader);
	return 0;
}

static int
next(struct fixture *f, int expected, uint16_t active)
{
	uint16_t word = 0xaaaa;
	bool supplied = false;
	st_big_loop_reader_begin(&f->reader);
	CHECK(st_big_loop_poll(&f->reader,&f->loop,&f->sink,&word,&supplied) == 0);
	CHECK(supplied && word == WORD(expected) && f->loop.active == active);
	CHECK(f->loop.command_read);
	unsigned delays = f->delays, keys = f->keys, randoms = f->randoms;
	uint16_t index = f->loop.index;
	CHECK(st_big_loop_poll(&f->reader,&f->loop,&f->sink,&word,&supplied) == 0);
	CHECK(supplied && word == WORD(expected) && f->loop.index == index);
	CHECK(f->delays == delays && f->keys == keys && f->randoms == randoms);
	return 0;
}

static int
literal_sequences(void)
{
	/* Hand-derived sequence/current results, never generated by this engine. */
	static const struct {
		int from,to,step; uint16_t type;
		int words[5]; size_t count;
		int expected[8]; size_t size; int current;
	} vectors[] = {
		{0,2,1,',',{0x8001},1,{0,1,2},3,2},
		{0,2,1,',',{7,8},2,{7,8,7,8},4,2},
		{10,20,5,',',{0x8002},1,{10,5,0},3,20},
		{5,1,2,',',{0x8001},1,{5,3,1},3,1},
		{5,1,0,',',{0x8001},1,{5},1,5},
		{0,2,1,'|',{0x8001},1,{0,0,1,1,2},5,2},
		{0,3,2,',',{0x8001},1,{0,2,4},3,4},
		{5,5,1,',',{0,-10000,-20000},3,{0,5,-5},3,5},
		{-20000,-20000,1,',',{-1},1,{29999},1,-20000},
		{-5,-3,1,',',{0x8001},1,{0,0,0},3,-3},
		{0,0,1,',',{-30000,-29999,-10000,-20000,0},5,{-30000,9999,0,0,0},5,0},
		{5,1,0x8000,',',{0x8001},1,{5,-32763},2,-32763},
	};
	for (size_t v = 0; v < sizeof(vectors)/sizeof(*vectors); ++v) {
		struct fixture f;
		CHECK(setup(&f,vectors[v].from,vectors[v].to,vectors[v].step,
		    vectors[v].type,vectors[v].words,vectors[v].count) == 0);
		for (size_t i = 0; i < vectors[v].size; ++i)
			CHECK(next(&f,vectors[v].expected[i],i+1 == vectors[v].size ? 0 : 1) == 0);
		CHECK(f.loop.current == WORD(vectors[v].current) && f.loop.index == 0);
		CHECK(f.keys == vectors[v].size && f.randoms == 0);
		CHECK(f.delays == (vectors[v].size+vectors[v].count-1)/vectors[v].count);
		uint16_t word = 0xaaaa; bool supplied = true;
		st_big_loop_reader_begin(&f.reader);
		CHECK(st_big_loop_poll(&f.reader,&f.loop,&f.sink,&word,&supplied) == 0);
		CHECK(!supplied && word == 0xaaaa); /* Next call belongs to the wire. */
	}
	return 0;
}

static int
publication_and_words(void)
{
	struct st_big_loop loop;
	st_big_loop_init(&loop);
	loop.count = 1; loop.words[0] = 0x8001; loop.words[2] = 12345;
	loop.current = 5; loop.origin = 999; loop.saved = 123; loop.varying_count = 77;
	loop.index = loop.pass = loop.varying_total = 9;
	loop.random_suppression = loop.first_text = 1;
	CHECK(st_big_loop_publish(&loop) == 0);
	CHECK(loop.active == 1 && loop.index == 0 && loop.pass == 0 && loop.varying_total == 0);
	CHECK(loop.no_parameters == 1 && loop.random_suppression == 0 && loop.first_text == 0);
	CHECK(loop.origin == 999 && loop.saved == 123 && loop.varying_count == 77 && loop.words[2] == 12345);
	CHECK(st_big_loop_scan(&loop) == 0 && loop.no_parameters == 0);
	loop.words[0] = 0x8003;
	CHECK(st_big_loop_publish(&loop) == 0 && st_big_loop_scan(&loop) == 0 && loop.no_parameters == 1);
	/* Signed coordinates and pass/cumulative counters wrap, never saturate. */
	const int x[] = {0x8001};
	struct fixture f;
	CHECK(setup(&f,32766,32767,2,',',x,1) == 0);
	CHECK(next(&f,32766,1) == 0 && next(&f,-32768,1) == 0);
	CHECK(f.loop.current == 0x8000);
	CHECK(st_big_loop_setup_step(5,1,0x8000) == 0x8000);
	CHECK(st_big_loop_setup_step(5,1,0) == 1);
	CHECK(setup(&f,10,100,1,',',x,1) == 0);
	f.loop.varying_total = 1; f.loop.pass = UINT16_MAX;
	CHECK(next(&f,11,1) == 0 && f.loop.pass == 0 && f.loop.varying_total == 2);
	int table[ST_BIG_LOOP_CAPACITY];
	for (size_t i = 0; i < ST_BIG_LOOP_CAPACITY; ++i) table[i] = 0x8001;
	CHECK(setup(&f,0,40,1,',',table,ST_BIG_LOOP_CAPACITY) == 0);
	for (int pass = 0; pass < 32; ++pass)
		for (size_t i = 0; i < ST_BIG_LOOP_CAPACITY; ++i) CHECK(next(&f,pass,1) == 0);
	CHECK(f.loop.current == 31 && f.loop.varying_total == 0 && f.loop.index == 0);
	CHECK(next(&f,31,1) == 0 && f.loop.varying_total == 1); /* Reachable duplicate after wrap. */
	return 0;
}

static int
waits_keys_and_random(void)
{
	struct fixture f;
	const int x[] = {0x8001}, r[] = {0x8003}, literal[] = {7};
	uint16_t word = 0xaaaa; bool supplied = true;
	CHECK(setup(&f,0,2,1,',',x,1) == 0);
	f.hold_delay = true; f.loop.delay = 5;
	CHECK(st_big_loop_poll(&f.reader,&f.loop,&f.sink,&word,&supplied) == IO_ERROR_IN_PROGRESS);
	CHECK(!supplied && word == 0xaaaa && f.delays == 1 && f.keys == 0 && f.loop.varying_total == 0);
	f.loop.delay = 2; f.hold_delay = false;
	CHECK(st_big_loop_poll(&f.reader,&f.loop,&f.sink,&word,&supplied) == 0);
	CHECK(supplied && word == 0 && f.last_delay == 2 && f.delay_retries == 1 && f.keys == 1);
	/* A delayed key checkpoint cannot repeat an already calculated operand. */
	CHECK(setup(&f,0,2,1,',',x,1) == 0); f.hold_key = true;
	CHECK(st_big_loop_poll(&f.reader,&f.loop,&f.sink,&word,&supplied) == IO_ERROR_IN_PROGRESS);
	CHECK(!supplied && f.loop.varying_total == 1 && f.loop.index == 0 && !f.loop.command_read);
	f.loop.words[0] = 99; f.hold_key = false;
	CHECK(st_big_loop_poll(&f.reader,&f.loop,&f.sink,&word,&supplied) == 0);
	CHECK(supplied && word == 0 && f.loop.varying_total == 1 && f.delays == 1 && f.keys == 2);
	/* Cancellation still performs literal stepping and the final W marker. */
	CHECK(setup(&f,0,2,1,',',literal,1) == 0); f.cancel = true; f.loop.command = 'W';
	CHECK(next(&f,7,0) == 0 && f.loop.current == 1 && f.loop.type == 'Z');
	CHECK(setup(&f,0,0,1,'@',literal,1) == 0); f.loop.command = 'W';
	CHECK(next(&f,7,0) == 0 && f.loop.type == '@');
	/* The previous command is used while evaluating a gang selector. */
	CHECK(setup(&f,0,0,1,',',literal,1) == 0); f.loop.command = 'C';
	CHECK(next(&f,7,0) == 0 && f.loop.type == ',');
	/* Even cancellation/endpoint termination cannot skip final random work. */
	CHECK(setup(&f,0,0,1,',',r,1) == 0);
	f.loop.command = 'W'; f.cancel = true; f.lower = f.upper = 10;
	CHECK(st_big_loop_poll(&f.reader,&f.loop,&f.sink,&word,&supplied) == IO_ERROR_IN_PROGRESS);
	CHECK(!supplied && f.loop.active == 0 && f.loop.current == 1 && f.loop.index == 0);
	CHECK(f.loop.type == 'Z' && !f.loop.command_read && f.keys == 1 && f.delays == 1 && f.randoms == 1);
	f.lower = f.upper = 0; f.loop.random_suppression = 1; /* Already inside r_random. */
	CHECK(st_big_loop_poll(&f.reader,&f.loop,&f.sink,&word,&supplied) == 0);
	CHECK(supplied && word == 0 && f.loop.command_read && f.randoms == 2 && f.keys == 1 && f.delays == 1);
	CHECK(f.loop.current == 1 && f.loop.index == 0);
	CHECK(setup(&f,0,0,1,',',r,1) == 0); f.loop.random_suppression = 1;
	CHECK(next(&f,0x8003,0) == 0 && f.randoms == 0 && f.rng == 1);
	CHECK(setup(&f,-32765,-32765,1,',',x,1) == 0);
	CHECK(next(&f,2,0) == 0 && f.randoms == 1); /* Calculated WORD8003 also expands. */
	return 0;
}

static int
flags_errors_and_reset(void)
{
	struct fixture f;
	const int x[] = {0x8001};
	uint16_t word = 0xaaaa; bool supplied;
	CHECK(setup(&f,0,2,1,',',x,1) == 0);
	f.loop.active = 2; f.loop.command = 'W';
	CHECK(next(&f,0,2) == 0 && f.keys == 0 && f.delays == 0 && f.loop.index == 0 && f.loop.type == ',');
	f.loop.active = 0; st_big_loop_reader_begin(&f.reader);
	CHECK(st_big_loop_poll(&f.reader,&f.loop,&f.sink,&word,&supplied) == 0 && !supplied);
	f.loop.active = 1; /* A declined wire field stays declined. */
	CHECK(st_big_loop_poll(&f.reader,&f.loop,&f.sink,&word,&supplied) == 0 && !supplied && f.delays == 0);
	for (unsigned bad = 0; bad < 3; ++bad) {
		CHECK(setup(&f,0,2,1,',',x,1) == 0);
		if (bad == 0) f.loop.count = 0;
		if (bad == 1) f.loop.count = 2049;
		if (bad == 2) f.loop.index = UINT16_MAX;
		CHECK(st_big_loop_poll(&f.reader,&f.loop,&f.sink,&word,&supplied) == IO_ERROR_OUT_OF_RANGE);
		CHECK(!supplied && f.delays == 0 && f.keys == 0 && !f.loop.command_read);
	}
	CHECK(setup(&f,0,2,1,',',x,1) == 0); f.key_error = IO_ERROR_IO;
	CHECK(st_big_loop_poll(&f.reader,&f.loop,&f.sink,&word,&supplied) == IO_ERROR_IO);
	CHECK(f.loop.varying_total == 1 && f.loop.index == 0 && !f.loop.command_read);
	CHECK(st_big_loop_poll(&f.reader,&f.loop,&f.sink,&word,&supplied) == IO_ERROR_IO && f.keys == 1);
	st_big_loop_reader_cancel(&f.reader);
	CHECK(st_big_loop_poll(&f.reader,&f.loop,&f.sink,&word,&supplied) == IO_ERROR_INVALID_ARGUMENT);
	f.key_error = 0; st_big_loop_reader_begin(&f.reader);
	CHECK(st_big_loop_poll(&f.reader,&f.loop,&f.sink,&word,&supplied) == 0 && supplied && word == 1);
	CHECK(f.loop.varying_total == 2); /* Earlier effects survive an error. */
	struct st_big_loop_reader before;
	memcpy(&before,&f.reader,sizeof(before));
	CHECK(st_big_loop_poll(&f.reader,&f.loop,NULL,&word,&supplied) == IO_ERROR_INVALID_ARGUMENT);
	CHECK(memcmp(&before,&f.reader,sizeof(before)) == 0);
	CHECK(setup(&f,0,2,1,',',x,1) == 0); f.hold_delay = true;
	CHECK(st_big_loop_poll(&f.reader,&f.loop,&f.sink,&word,&supplied) == IO_ERROR_IN_PROGRESS);
	f.loop.index = 2048; f.hold_delay = false;
	CHECK(st_big_loop_poll(&f.reader,&f.loop,&f.sink,&word,&supplied) == IO_ERROR_OUT_OF_RANGE);
	CHECK(f.delays == 2 && f.keys == 0 && !f.loop.command_read);
	return 0;
}

/* This test adapter composes the two real readers through the generic
 * source/wire boundary; it does not implement BIG command dispatch. */
struct receive {
	struct fixture fixture;
	struct st_big_number_reader number;
	struct st_big_number_context context;
	size_t fields, commands, text_size;
	uint8_t text[16];
	int values[4];
};

static int
ordinary_text(void *context, const uint8_t *bytes, size_t size)
{
	struct receive *r = context;
	CHECK(size <= sizeof(r->text)-r->text_size);
	if (size != 0) memcpy(r->text+r->text_size,bytes,size);
	r->text_size += size;
	return 0;
}

static int
field(void *context, const struct st_graphics_command_view *view,
    const struct st_graphics_parameter *parameter)
{
	struct receive *r = context;
	(void)view;
	CHECK(parameter->kind == ST_GRAPHICS_NUMBER);
	st_big_loop_reader_begin(&r->fixture.reader);
	st_big_number_begin(&r->number);
	r->context.y_coordinate = parameter->axis == ST_GRAPHICS_Y;
	++r->fields;
	return 0;
}

static int
source(void *context, const struct st_graphics_command_view *view,
    const struct st_graphics_parameter *parameter, int *value, bool *supplied)
{
	struct receive *r = context;
	(void)view; (void)parameter;
	uint16_t word = 0;
	int status = st_big_loop_poll(&r->fixture.reader,&r->fixture.loop,&r->fixture.sink,&word,supplied);
	*value = (int)st_big_number_signed(word);
	return status;
}

static int
wire_number(void *context, const struct st_graphics_command_view *view,
    const struct st_graphics_parameter *parameter, const uint8_t *bytes,
    size_t size, size_t *accepted, int *value, bool *complete)
{
	struct receive *r = context;
	(void)view; (void)parameter;
	struct st_big_number_result result;
	int status = st_big_number_feed(&r->number,&r->context,bytes,size,false,accepted,&result);
	*complete = result.complete;
	*value = (int)st_big_number_signed(result.word);
	if (status == 0 && *complete) r->fixture.loop.command_read = true;
	return status;
}

static int
command(void *context, const struct st_graphics_command_view *view)
{
	struct receive *r = context;
	CHECK(view->code == 'L' && view->count == 4);
	for (size_t i = 0; i < 4; ++i) {
		CHECK(view->arguments[i].has_value);
		r->values[i] = view->arguments[i].value;
	}
	++r->commands;
	return 0;
}

static int
parser_create(st_graphics_parser_t **parser, struct receive *r,
    struct st_graphics_parser_sink *sink)
{
	static const uint8_t attention[] = {'I','#'};
	static const struct st_graphics_dialect dialect = {
		.attention = attention,.attention_size = 2,.chain_indicator = true,.chain = '>',.number_digits = 4,
	};
	static const struct st_graphics_parameter line[] = {
		{.kind = ST_GRAPHICS_NUMBER,.axis = ST_GRAPHICS_X},
		{.kind = ST_GRAPHICS_NUMBER,.axis = ST_GRAPHICS_Y},
		{.kind = ST_GRAPHICS_NUMBER,.axis = ST_GRAPHICS_X},
		{.kind = ST_GRAPHICS_NUMBER,.axis = ST_GRAPHICS_Y},
	};
	static const struct st_graphics_command commands[] = {{'L',line,4,NULL}};
	static const struct st_graphics_parser_config config = {
		.dialect = &dialect,.commands = commands,.command_count = 1,.max_arguments = 4,
	};
	memset(r,0,sizeof(*r));
	const int data[] = {10,5};
	CHECK(setup(&r->fixture,0,0,1,',',data,2) == 0);
	r->context = (struct st_big_number_context){.scaling = 3,.resolution = 3};
	*sink = (struct st_graphics_parser_sink){.context = r,.text = ordinary_text,
		.field = field,.number = source,.read_number = wire_number,.command = command};
	return st_graphics_parser_create(parser,&config);
}

static int
shared_parser(void)
{
	static const uint8_t wire[] = "I#L 20,5:tail";
	for (size_t split = 0; split <= sizeof(wire); ++split) {
		struct receive r;
		struct st_graphics_parser_sink sink;
		st_graphics_parser_t *parser = NULL;
		size_t used;
		CHECK(parser_create(&parser,&r,&sink) == 0);
		if (split < sizeof(wire)) {
			CHECK(st_graphics_parser_feed(parser,&sink,wire,split,&used) == 0 && used == split);
			CHECK(st_graphics_parser_feed(parser,&sink,wire+split,sizeof(wire)-1-split,&used) == 0 && used == sizeof(wire)-1-split);
		} else {
			for (size_t i = 0; i < sizeof(wire)-1; ++i)
				CHECK(st_graphics_parser_feed(parser,&sink,wire+i,1,&used) == 0 && used == 1);
		}
		CHECK(r.fields == 4 && r.commands == 1 && r.fixture.loop.active == 0);
		CHECK(r.values[0] == 10 && r.values[1] == 5 && r.values[2] == 20 && r.values[3] == 11);
		CHECK(r.fixture.delays == 1 && r.fixture.keys == 2 && r.fixture.randoms == 0);
		CHECK(r.text_size == 4 && memcmp(r.text,"tail",4) == 0);
		st_graphics_parser_destroy(parser);
	}
	struct receive r;
	struct st_graphics_parser_sink sink;
	st_graphics_parser_t *parser = NULL;
	size_t used;
	CHECK(parser_create(&parser,&r,&sink) == 0); r.fixture.hold_delay = true;
	CHECK(st_graphics_parser_feed(parser,&sink,wire,sizeof(wire)-1,&used) == IO_ERROR_IN_PROGRESS && used == 4);
	CHECK(r.fields == 1 && r.commands == 0 && r.fixture.delays == 1 && r.fixture.keys == 0);
	CHECK(st_graphics_parser_resume(parser) == IO_ERROR_INVALID_ARGUMENT);
	r.fixture.hold_delay = false;
	CHECK(st_graphics_parser_feed(parser,&sink,wire+4,sizeof(wire)-5,&used) == 0 && used == sizeof(wire)-5);
	CHECK(r.commands == 1 && r.fields == 4 && r.values[1] == 5 && r.values[3] == 11);
	CHECK(r.fixture.delays == 2 && r.fixture.delay_retries == 1 && r.fixture.keys == 2);
	st_graphics_parser_destroy(parser);
	/* A pending random tail stays the source even after its endpoint cleared
	 * loop mode. It must finish before the remaining wire fields can start. */
	CHECK(parser_create(&parser,&r,&sink) == 0);
	r.fixture.loop.count = 1; r.fixture.loop.words[0] = 0x8003;
	CHECK(st_big_loop_publish(&r.fixture.loop) == 0 && st_big_loop_scan(&r.fixture.loop) == 0);
	r.fixture.lower = r.fixture.upper = 10;
	const uint8_t random_wire[] = "I#L 5,20,5:tail";
	CHECK(st_graphics_parser_feed(parser,&sink,random_wire,sizeof(random_wire)-1,&used) == IO_ERROR_IN_PROGRESS && used == 4);
	CHECK(r.fixture.loop.active == 0 && r.fields == 1 && r.fixture.randoms == 1);
	r.fixture.lower = r.fixture.upper = 0;
	CHECK(st_graphics_parser_feed(parser,&sink,random_wire+4,sizeof(random_wire)-5,&used) == 0 && used == sizeof(random_wire)-5);
	CHECK(r.commands == 1 && r.values[0] == 0 && r.values[1] == 11 && r.values[2] == 20 && r.values[3] == 11);
	CHECK(r.fixture.randoms == 2 && r.fixture.keys == 1 && r.fixture.delays == 1);
	st_graphics_parser_destroy(parser);
	/* An explicit EOF cancels the grammar without resuming its waiting source. */
	CHECK(parser_create(&parser,&r,&sink) == 0); r.fixture.hold_delay = true;
	CHECK(st_graphics_parser_feed(parser,&sink,wire,sizeof(wire)-1,&used) == IO_ERROR_IN_PROGRESS && used == 4);
	CHECK(st_graphics_parser_finish(parser,&sink) == IO_ERROR_PROTOCOL && r.fixture.delays == 1);
	st_big_loop_reader_cancel(&r.fixture.reader); r.fixture.loop.active = 0;
	CHECK(st_graphics_parser_feed(parser,&sink,(const uint8_t *)"I#L 1,2,3,4:",12,&used) == 0 && used == 12);
	CHECK(r.commands == 1 && r.values[0] == 1 && r.values[1] == 4 && r.values[2] == 3 && r.values[3] == 9);
	CHECK(r.fixture.delays == 1 && r.fixture.keys == 0);
	st_graphics_parser_destroy(parser);
	return 0;
}

int
main(void)
{
	CHECK(literal_sequences() == 0);
	CHECK(publication_and_words() == 0);
	CHECK(waits_keys_and_random() == 0);
	CHECK(flags_errors_and_reset() == 0);
	CHECK(shared_parser() == 0);
	return 0;
}
