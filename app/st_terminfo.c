int
st_terminfo_write(FILE *stream)
{
	if (stream == NULL)
		return -1;
	for (size_t i = 0; i < sizeof(parts) / sizeof(parts[0]); ++i) {
		if (fputs(parts[i], stream) == EOF)
			return -1;
	}
	return 0;
}

