import argparse
import hashlib
import pathlib
import urllib.request


VERSION = "17.0.0"
SOURCES = {
    "unicode": (
        f"UnicodeData-{VERSION}.txt",
        f"https://www.unicode.org/Public/{VERSION}/ucd/UnicodeData.txt",
        "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
    ),
    "derived": (
        f"DerivedNormalizationProps-{VERSION}.txt",
        f"https://www.unicode.org/Public/{VERSION}/ucd/DerivedNormalizationProps.txt",
        "71fd6a206a2c0cdd41feb6b7f656aa31091db45e9cedc926985d718397f9e488",
    ),
}


def source_bytes(name, source_dir):
    filename, url, expected = SOURCES[name]
    if source_dir is None:
        with urllib.request.urlopen(url) as response:
            data = response.read()
    else:
        data = (source_dir / filename).read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != expected:
        raise ValueError(f"{filename}: expected SHA-256 {expected}, got {actual}")
    return data


def parse_unicode_data(data):
    combining = {}
    raw_decompositions = {}
    for line_number, raw in enumerate(data.decode("utf-8").splitlines(), 1):
        fields = raw.split(";")
        if len(fields) != 15:
            raise ValueError(f"UnicodeData:{line_number}: expected 15 fields")
        codepoint = int(fields[0], 16)
        ccc = int(fields[3])
        if ccc:
            combining[codepoint] = ccc
        encoded = fields[5]
        if encoded and not encoded.startswith("<"):
            raw_decompositions[codepoint] = tuple(
                int(value, 16) for value in encoded.split())
    return combining, raw_decompositions


def parse_exclusions(data):
    excluded = set()
    for line_number, raw in enumerate(data.decode("utf-8-sig").splitlines(), 1):
        content = raw.split("#", 1)[0].strip()
        if not content:
            continue
        encoded, prop, *_ = (part.strip() for part in content.split(";"))
        if prop != "Full_Composition_Exclusion":
            continue
        try:
            if ".." in encoded:
                first, last = (int(value, 16) for value in encoded.split(".."))
            else:
                first = last = int(encoded, 16)
        except ValueError as error:
            raise ValueError(
                f"DerivedNormalizationProps:{line_number}: malformed range") from error
        excluded.update(range(first, last + 1))
    return excluded


def full_decompositions(raw):
    result = {}

    def expand(codepoint, active):
        if codepoint not in raw:
            return (codepoint,)
        if codepoint in result:
            return result[codepoint]
        if codepoint in active:
            raise ValueError(f"recursive decomposition for U+{codepoint:04X}")
        expanded = tuple(value for part in raw[codepoint]
                         for value in expand(part, active | {codepoint}))
        result[codepoint] = expanded
        return expanded

    for codepoint in raw:
        expand(codepoint, set())
    return result


def ranges(values):
    result = []
    for codepoint, value in sorted(values.items()):
        if result and codepoint == result[-1][1] + 1 and value == result[-1][2]:
            result[-1] = (result[-1][0], codepoint, value)
        else:
            result.append((codepoint, codepoint, value))
    return result


def write_source(path, combining, decompositions, raw, exclusions):
    decomposition_data = []
    decomposition_rows = []
    for codepoint, values in sorted(decompositions.items()):
        offset = len(decomposition_data)
        decomposition_data.extend(values)
        decomposition_rows.append((codepoint, offset, len(values)))
    compositions = sorted((values[0], values[1], codepoint)
                          for codepoint, values in raw.items()
                          if len(values) == 2 and codepoint not in exclusions)
    with path.open("w", encoding="ascii", newline="\n") as out:
        out.write("/* Generated by unicode_normalization/update_unicode_normalization.py; do not edit. */\n")
        out.write(f"/* Unicode {VERSION}; see unicode_normalization/UPSTREAM.md. */\n\n")
        out.write("/*\n * Copyright (c) 2026 Stephen Hurd\n")
        out.write(" * SPDX-License-Identifier: BSD-2-Clause AND Unicode-3.0\n */\n\n")
        out.write('#include "st_unicode_normalization.h"\n\n')
        out.write("struct ccc_range { uint32_t first; uint32_t last; uint8_t value; };\n")
        out.write("struct decomposition { uint32_t codepoint; uint32_t offset; uint8_t count; };\n")
        out.write("struct composition { uint32_t first; uint32_t second; uint32_t result; };\n\n")
        out.write("static const struct ccc_range ccc_ranges[] = {\n")
        for first, last, value in ranges(combining):
            out.write(f"\t{{UINT32_C(0x{first:x}), UINT32_C(0x{last:x}), {value}}},\n")
        out.write("};\n\nstatic const uint32_t decomposition_data[] = {\n")
        for offset in range(0, len(decomposition_data), 8):
            values = decomposition_data[offset:offset + 8]
            out.write("\t" + ", ".join(
                f"UINT32_C(0x{value:x})" for value in values) + ",\n")
        out.write("};\n\nstatic const struct decomposition decompositions[] = {\n")
        for codepoint, offset, count in decomposition_rows:
            out.write(f"\t{{UINT32_C(0x{codepoint:x}), {offset}, {count}}},\n")
        out.write("};\n\nstatic const struct composition compositions[] = {\n")
        for first, second, result in compositions:
            out.write(f"\t{{UINT32_C(0x{first:x}), UINT32_C(0x{second:x}), UINT32_C(0x{result:x})}},\n")
        out.write("};\n\n")
        out.write(r'''static bool
scalar(uint32_t codepoint)
{
	return codepoint <= UINT32_C(0x10ffff)
	    && !(codepoint >= UINT32_C(0xd800) && codepoint <= UINT32_C(0xdfff));
}

uint8_t
st_unicode_canonical_combining_class(uint32_t codepoint)
{
	size_t left = 0;
	size_t right = sizeof(ccc_ranges) / sizeof(ccc_ranges[0]);

	while (left < right) {
		size_t middle = left + (right - left) / 2;

		if (ccc_ranges[middle].last < codepoint)
			left = middle + 1;
		else
			right = middle;
	}
	return left < sizeof(ccc_ranges) / sizeof(ccc_ranges[0])
	    && ccc_ranges[left].first <= codepoint ? ccc_ranges[left].value : 0;
}

size_t
st_unicode_canonical_decompose(uint32_t codepoint, uint32_t *output,
	size_t capacity)
{
	size_t left = 0;
	size_t right = sizeof(decompositions) / sizeof(decompositions[0]);
	uint32_t hangul_index;
	uint32_t values[3];
	size_t count;

	if (!scalar(codepoint) || (output == NULL && capacity != 0))
		return 0;
	if (codepoint >= UINT32_C(0xac00) && codepoint < UINT32_C(0xd7a4)) {
		hangul_index = codepoint - UINT32_C(0xac00);
		values[0] = UINT32_C(0x1100) + hangul_index / 588;
		values[1] = UINT32_C(0x1161) + (hangul_index % 588) / 28;
		values[2] = UINT32_C(0x11a7) + hangul_index % 28;
		count = values[2] == UINT32_C(0x11a7) ? 2 : 3;
		if (capacity >= count)
			for (size_t i = 0; i < count; ++i)
				output[i] = values[i];
		return count;
	}
	while (left < right) {
		size_t middle = left + (right - left) / 2;

		if (decompositions[middle].codepoint < codepoint)
			left = middle + 1;
		else
			right = middle;
	}
	if (left == sizeof(decompositions) / sizeof(decompositions[0])
	    || decompositions[left].codepoint != codepoint) {
		if (capacity >= 1)
			output[0] = codepoint;
		return 1;
	}
	count = decompositions[left].count;
	if (capacity >= count)
		for (size_t i = 0; i < count; ++i)
			output[i] = decomposition_data[decompositions[left].offset + i];
	return count;
}

bool
st_unicode_canonical_compose(uint32_t first, uint32_t second,
	uint32_t *composition)
{
	size_t left = 0;
	size_t right = sizeof(compositions) / sizeof(compositions[0]);

	if (composition == NULL || !scalar(first) || !scalar(second))
		return false;
	if (first >= UINT32_C(0x1100) && first <= UINT32_C(0x1112)
	    && second >= UINT32_C(0x1161) && second <= UINT32_C(0x1175)) {
		*composition = UINT32_C(0xac00) + (first - UINT32_C(0x1100)) * 588
		    + (second - UINT32_C(0x1161)) * 28;
		return true;
	}
	if (first >= UINT32_C(0xac00) && first < UINT32_C(0xd7a4)
	    && (first - UINT32_C(0xac00)) % 28 == 0
	    && second > UINT32_C(0x11a7) && second <= UINT32_C(0x11c2)) {
		*composition = first + second - UINT32_C(0x11a7);
		return true;
	}
	while (left < right) {
		size_t middle = left + (right - left) / 2;

		if (compositions[middle].first < first
		    || (compositions[middle].first == first
		    && compositions[middle].second < second))
			left = middle + 1;
		else
			right = middle;
	}
	if (left == sizeof(compositions) / sizeof(compositions[0])
	    || compositions[left].first != first
	    || compositions[left].second != second)
		return false;
	*composition = compositions[left].result;
	return true;
}
''')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source-dir", type=pathlib.Path)
    parser.add_argument("--root", type=pathlib.Path,
                        default=pathlib.Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    combining, raw = parse_unicode_data(source_bytes("unicode", args.source_dir))
    exclusions = parse_exclusions(source_bytes("derived", args.source_dir))
    output = args.root / "unicode_normalization" / "generated"
    output.mkdir(parents=True, exist_ok=True)
    write_source(output / "st_unicode_normalization.c", combining,
                 full_decompositions(raw), raw, exclusions)


if __name__ == "__main__":
    main()
